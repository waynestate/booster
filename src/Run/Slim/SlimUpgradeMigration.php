<?php

declare(strict_types=1);

namespace Waynestate\Booster\Run\Slim;

use Composer\Semver\VersionParser;
use Throwable;
use Waynestate\Booster\Hop\Hop;
use Waynestate\Booster\Packaging\RunScratch;
use Waynestate\Booster\Run\ComposerEditor;
use Waynestate\Booster\Run\FrameworkEngine;
use Waynestate\Booster\Run\VendoredMigrationResult;
use Waynestate\Booster\ToolError;

/**
 * The SlimUpgrade engine: moves a Slim 3 app to Slim 4 over its own Pimple
 * container. It writes the generated glue (LegacyStubs) under the app's PSR-4
 * root, rewrites the bootstrap (BootstrapRewriter) and the route and
 * middleware code (RouteRewriter, then AdderWidener for route adders a group
 * calls), moves Slim 3's own request and response types onto slim/http
 * (SlimHttpRewriter), applies the hop's Composer pins plus Pimple, slim/psr7
 * and, when the app needs it, slim/http, and lists what only a person can do
 * as MANUAL lines. A dry run writes nothing
 * and says what it would do; a second run changes nothing.
 *
 * Slim 3 to 4 is the difficult second album: same band, new label, and the
 * container quit to go solo. This engine books the session musicians.
 */
final class SlimUpgradeMigration implements FrameworkEngine
{
    /** Folders never searched, at any depth. */
    private const SKIP_DIRS = ['vendor', 'node_modules', '.git', 'tmp', 'logs', 'cache', 'storage'];

    /** Top-level folders whose PHP files the route rewrite reads. */
    private const ROUTE_DIRS = ['src', 'app', 'routes', 'config'];

    /** Top-level folders whose PHP files the Slim\Http rewrite reads (the bootstrap files too). */
    private const HTTP_DIRS = ['src', 'app', 'routes', 'config', 'tests', 'public'];

    /** Text that sends a file through RouteRewriter. */
    private const ROUTE_TRIGGERS = ['->group(', '->add(', "getAttribute('route')", 'getAttribute("route")', 'pathFor('];

    /** The first comment line of every generated glue file; such files are never rewritten. */
    private const GLUE_MARKER = 'Generated by Booster for the Slim 3 to 4 move';

    public const NO_PSR4 = 'The app has no PSR-4 autoload entry to put the Slim 4 glue in.';

    public const ERROR_HANDLER_LINE = "MANUAL: route exceptions now reach Slim's ErrorMiddleware before the app's own PHP error or exception handler;"
        . ' register that handler on the error middleware if you want the old page and logging.';

    public const ENVIRONMENT_NOTE = 'Slim\\Http\\Environment is gone in Slim 4; build test requests with Slim\\Psr7\\Factory\\ServerRequestFactory'
        . ' or Slim\\Http\\Factory\\DecoratedServerRequestFactory.';

    public const TWIG_NOTE = 'Twig-View 3 has no path_for; use url_for from the Twig-View runtime extension';

    /**
     * Packages the move needs beside the hop's own pins: the constraint, whether
     * only an app that already lists the package gets it, and why.
     *
     * @var array<string, array{string, bool, string}>
     */
    private const EXTRA_PINS = [
        'pimple/pimple' => ['^3', false, 'Slim 4 ships no container; the legacy container is Pimple'],
        'slim/psr7' => ['^1.6', false, 'the PSR-7 messages the glue builds'],
        'slim/twig-view' => ['^3.4', true, 'Twig-View 3 is the Slim 4 line'],
        'twig/twig' => ['^3.8', true, 'Twig-View 3 needs Twig 3'],
    ];

    /**
     * The pin for an app whose code names Slim 3's Slim\Http\Request,
     * Response or Environment.
     *
     * @var array<string, array{string, bool, string}>
     */
    private const HTTP_PIN = [
        'slim/http' => ['^1.3', false, "the decorators that keep withJson, write and getParam for the app's Slim\\Http\\Request and Response types"],
    ];

    /** Past-tense first words of change lines and their dry-run form. */
    private const WOULD = [
        'Wrote' => 'write', 'Rewrote' => 'rewrite', 'Replaced' => 'replace', 'Added' => 'add', 'Set' => 'set',
        'Removed' => 'remove', 'Wrapped' => 'wrap', 'Widened' => 'widen',
    ];

    public function __construct(private readonly ComposerEditor $composer) {}

    public function migrate(string $appPath, bool $dryRun, string $php, ?Hop $hop = null): VendoredMigrationResult
    {
        $appPath = rtrim($appPath, '/\\');
        if ($hop === null) {
            return self::refuse('The Slim upgrade engine runs for its hop (slim-3-to-4), and none was given.');
        }
        $composerFile = $appPath . '/composer.json';
        if (!is_file($composerFile)) {
            return self::refuse('There is no composer.json, so Booster cannot tell which Slim the app runs or move its packages.');
        }
        $composerRaw = (string) file_get_contents($composerFile);
        $composerData = json_decode($composerRaw, true);
        if (!is_array($composerData)) {
            return self::refuse('composer.json is not valid JSON.');
        }
        if (!isset($composerData['require']['slim/slim']) && !isset($composerData['require-dev']['slim/slim'])) {
            return self::refuse('composer.json does not require slim/slim, so this is not a Slim app.');
        }

        $sources = [];
        foreach (self::files($appPath, 'php') as $file) {
            $source = (string) file_get_contents($appPath . '/' . $file);
            if (!str_contains($source, self::GLUE_MARKER)) {
                $sources[$file] = $source;
            }
        }
        $bootstraps = array_values(array_filter(array_keys($sources), static fn(string $file): bool => self::isBootstrap($sources[$file])));
        if ($bootstraps === []) {
            return self::refuse('Found no PHP file that builds the Slim app (new \\Slim\\App(...)), so there is no bootstrap to rewrite.');
        }
        $root = self::psr4Root($composerData);
        if ($root === null) {
            return self::refuse(self::NO_PSR4);
        }
        [$namespace, $glueDir] = $root;

        // Each changed file's content before ('' for a new file) and after.
        $before = [];
        $after = [];
        $changes = [];
        $manual = [];

        // 1. The glue.
        $written = [];
        foreach (self::glue($namespace, $glueDir) as $file => [$class, $content]) {
            $full = $appPath . '/' . $file;
            if (!is_file($full)) {
                $before[$file] = '';
                $after[$file] = $content;
                $written[] = $class;
            } elseif ((string) file_get_contents($full) !== $content) {
                $manual[] = sprintf('MANUAL: %s exists and differs from the glue this hop writes, so it was left as is; compare it with the generated %s by hand.', $file, $class);
            }
        }
        if (count($written) === 3) {
            $changes[] = sprintf('Wrote the legacy container, double-pass adapter and app glue in %s.', $glueDir);
        } elseif ($written !== []) {
            $changes[] = sprintf('Wrote %s in %s.', implode(', ', $written), $glueDir);
        }

        // 2. The bootstrap files.
        $bootstrapRewriter = new BootstrapRewriter();
        foreach ($bootstraps as $file) {
            $result = $bootstrapRewriter->rewrite($sources[$file], $namespace);
            if ($result['code'] !== $sources[$file]) {
                $before[$file] = $sources[$file];
                $after[$file] = $result['code'];
                $changes[] = sprintf('Rewrote the bootstrap in %s.', $file);
                foreach (array_count_values($result['changes']) as $line => $count) {
                    $changes[] = self::inFile((string) $line, $file, $count);
                }
            }
            $manual = [...$manual, ...self::fileManual($result['manual'], $file)];
        }

        // 3. Routes and middleware.
        $routeManual = [];
        $groupRewritten = false;
        $routeRewriter = new RouteRewriter();
        foreach (array_keys($sources) as $file) {
            if (!in_array($file, $bootstraps, true) && !in_array(explode('/', $file)[0], self::ROUTE_DIRS, true)) {
                continue;
            }
            $current = $after[$file] ?? $sources[$file];
            if (!self::containsAny($current, self::ROUTE_TRIGGERS)) {
                continue;
            }
            $result = $routeRewriter->rewrite($current, $namespace);
            if ($result['code'] !== $current) {
                $before[$file] ??= $sources[$file];
                $after[$file] = $result['code'];
            }
            foreach ($result['changes'] as $line) {
                $groupRewritten = $groupRewritten || str_contains($line, 'route group callable');
                $changes[] = self::inFile($line, $file, 1);
            }
            $routeManual[$file] = $result['manual'];
        }

        // 4. Route adders a group may call, anywhere in the app.
        if ($groupRewritten) {
            $current = [];
            foreach (array_keys($sources) as $file) {
                $current[$file] = $after[$file] ?? $sources[$file];
            }
            $widening = (new AdderWidener())->widen($current);
            foreach ($widening['files'] as $file => $code) {
                $before[$file] ??= $sources[$file];
                $after[$file] = $code;
                $count = count($widening['widened'][$file]);
                $changes[] = sprintf('Widened %d route adder parameter(s) from \\Slim\\App to RouteCollectorProxyInterface in %s, so a route group can call them.', $count, $file);
                foreach ($widening['widened'][$file] as $parameter) {
                    $prefix = sprintf('MANUAL: line %d: %s is typed \\Slim\\App in a route adder', $parameter['line'], $parameter['variable']);
                    $routeManual[$file] = array_values(array_filter(
                        $routeManual[$file] ?? [],
                        static fn(string $line): bool => !str_starts_with($line, $prefix),
                    ));
                }
            }
        }
        foreach ($routeManual as $file => $lines) {
            // Step 5 reports Slim\Http\Environment once per file, in every folder it reads.
            $lines = array_filter($lines, static fn(string $line): bool => !str_contains($line, 'uses Slim\\Http\\Environment'));
            $manual = [...$manual, ...self::fileManual(array_values($lines), $file)];
        }

        // 5. Slim 3's own request, response and environment classes.
        $usesHttp = false;
        $httpRewriter = new SlimHttpRewriter();
        foreach (array_keys($sources) as $file) {
            if (!in_array($file, $bootstraps, true) && !in_array(explode('/', $file)[0], self::HTTP_DIRS, true)) {
                continue;
            }
            $current = $after[$file] ?? $sources[$file];
            if (!self::containsAny(strtolower($current), ['request', 'response', 'environment'])) {
                continue;
            }
            $result = $httpRewriter->rewrite($current);
            $usesHttp = $usesHttp || $result['uses'];
            if ($result['code'] !== $current) {
                $before[$file] ??= $sources[$file];
                $after[$file] = $result['code'];
                $changes[] = self::inFile('Rewrote Slim\\Http\\Request to its slim/http decorator, Slim\\Http\\ServerRequest.', $file, $result['renamed']);
            }
            if ($result['environment'] !== []) {
                $manual[] = sprintf(
                    'MANUAL: %s: %s %s: %s',
                    $file,
                    count($result['environment']) === 1 ? 'line' : 'lines',
                    implode(', ', $result['environment']),
                    self::ENVIRONMENT_NOTE,
                );
            }
        }

        // 6. Composer.
        [$composerNew, $composerChanges, $packages] = $this->composerJson($hop, $composerRaw, $composerData, $usesHttp);
        if ($composerNew !== null) {
            $before['composer.json'] = $composerRaw;
            $after['composer.json'] = $composerNew;
            $changes = [...$changes, ...$composerChanges];
        }

        // 7. What only a person can do.
        $manual = [...$manual, ...self::twigManual($appPath), ...self::containerReadManual($sources, $after)];
        $manual[] = self::ERROR_HANDLER_LINE;
        $manual = array_values(array_unique($manual));

        $files = [];
        foreach ($after as $file => $content) {
            $files[] = ['file' => $file, 'diff' => UnifiedDiff::of($file, $before[$file] ?? '', $content)];
        }

        if ($after === []) {
            $changes[] = 'Nothing left to move: the app already runs on the Slim 4 glue.';
        } elseif ($dryRun) {
            $changes = array_map(self::would(...), $changes);
        } else {
            foreach ($after as $file => $content) {
                self::write($appPath . '/' . $file, $content);
            }
        }

        return new VendoredMigrationResult($changes, $files, $manual, [], $packages);
    }

    private static function refuse(string $reason): VendoredMigrationResult
    {
        return new VendoredMigrationResult([], [], [], [$reason]);
    }

    /** A file that builds the Slim app, or already builds it through the glue (a second run). */
    private static function isBootstrap(string $php): bool
    {
        return preg_match('/\bnew\s+\\\\?Slim\\\\App\s*\(/i', $php) === 1
            || (preg_match('/\bnew\s+App\s*\(/', $php) === 1 && preg_match('/\buse\s+\\\\?Slim\\\\App\s*;/i', $php) === 1)
            || preg_match('/\bLegacyApp::create\s*\(/', $php) === 1;
    }

    /**
     * The PSR-4 namespace and folder the glue goes in: the entry whose path is
     * src/, else the first. Null when composer.json has none.
     *
     * @param array<mixed> $composer
     *
     * @return array{string, string}|null the glue namespace and its folder, relative to the app
     */
    private static function psr4Root(array $composer): ?array
    {
        $map = $composer['autoload']['psr-4'] ?? null;
        if (!is_array($map) || $map === []) {
            return null;
        }
        $first = null;
        foreach ($map as $prefix => $paths) {
            foreach (is_array($paths) ? $paths : [$paths] as $path) {
                if (!is_string($path)) {
                    continue;
                }
                $path = rtrim((string) preg_replace('#^\./#', '', str_replace('\\', '/', trim($path))), '/');
                $candidate = [(string) $prefix, $path];
                $first ??= $candidate;
                if ($path === 'src') {
                    $first = $candidate;
                    break 2;
                }
            }
        }
        if ($first === null) {
            return null;
        }
        [$prefix, $path] = $first;
        $prefix = trim($prefix, '\\');

        return [
            $prefix === '' ? 'Legacy' : $prefix . '\\Legacy',
            $path === '' ? 'Legacy' : $path . '/Legacy',
        ];
    }

    /**
     * @return array<string, array{string, string}> file to [class, content]
     */
    private static function glue(string $namespace, string $dir): array
    {
        return [
            $dir . '/LegacyContainer.php' => ['LegacyContainer', LegacyStubs::container($namespace)],
            $dir . '/LegacyDoublePass.php' => ['LegacyDoublePass', LegacyStubs::doublePass($namespace)],
            $dir . '/LegacyApp.php' => ['LegacyApp', LegacyStubs::app($namespace)],
        ];
    }

    /**
     * The hop's pins through ComposerEditor (on a scratch copy, so a dry run
     * writes nothing), then Pimple, slim/psr7, the Twig-View line and, when
     * the app names Slim 3's HTTP classes, slim/http.
     *
     * @param array<mixed> $data
     *
     * @return array{?string, list<string>, list<string>} the new composer.json (null when unchanged), the lines, the packages touched
     */
    private function composerJson(Hop $hop, string $raw, array $data, bool $needsHttp): array
    {
        $scratch = RunScratch::dir('slim-upgrade/' . bin2hex(random_bytes(6)));
        self::write($scratch . '/composer.json', $raw);
        $lines = $this->composer->apply($hop, $scratch);
        $newRaw = (string) file_get_contents($scratch . '/composer.json');
        @unlink($scratch . '/composer.json');
        @rmdir($scratch);
        $new = json_decode($newRaw, true);
        if (!is_array($new)) {
            throw new ToolError('composer.json is not valid JSON after the Slim hop pins.');
        }

        $extra = [];
        $pins = $needsHttp ? [...self::EXTRA_PINS, ...self::HTTP_PIN] : self::EXTRA_PINS;
        foreach ($pins as $package => [$constraint, $onlyIfPresent, $why]) {
            $section = isset($new['require'][$package]) ? 'require' : (isset($new['require-dev'][$package]) ? 'require-dev' : null);
            if ($section === null) {
                if ($onlyIfPresent) {
                    continue;
                }
                $new['require'][$package] = $constraint;
                if (($new['config']['sort-packages'] ?? false) === true && is_array($new['require'])) {
                    $new['require'] = self::sortRequire($new['require']);
                }
                $extra[] = sprintf('Added %s %s to require (%s).', $package, $constraint, $why);
            } elseif (self::below((string) $new[$section][$package], $constraint)) {
                $new[$section][$package] = $constraint;
                $extra[] = sprintf('Set %s to %s in %s (%s).', $package, $constraint, $section, $why);
            }
        }
        if ($extra !== []) {
            $newRaw = json_encode($new, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
        }

        $packages = [];
        foreach (['require', 'require-dev'] as $section) {
            $old = is_array($data[$section] ?? null) ? $data[$section] : [];
            $now = is_array($new[$section] ?? null) ? $new[$section] : [];
            foreach (array_keys($old + $now) as $package) {
                if (($old[$package] ?? null) !== ($now[$package] ?? null)) {
                    $packages[] = (string) $package;
                }
            }
        }
        $packages = array_values(array_unique($packages));
        if ($packages === []) {
            // No package moved (a second run, or a hop pin the app already
            // meets), so composer.json stays byte for byte as it was.
            return [null, [], []];
        }

        return [$newRaw, [...$lines, ...$extra], $packages];
    }

    /** True when $current's floor is below $target's, so the pin raises it (or $current has no usable floor). */
    private static function below(string $current, string $target): bool
    {
        try {
            $parser = new VersionParser();
            $floor = $parser->parseConstraints($current)->getLowerBound()->getVersion();
            $targetFloor = $parser->parseConstraints($target)->getLowerBound()->getVersion();
        } catch (Throwable) {
            return true;
        }

        return version_compare($floor, $targetFloor, '<');
    }

    /**
     * Composer's sort-packages order: php, php-*, ext-*, lib-*, then the rest.
     *
     * @param array<mixed> $require
     *
     * @return array<mixed>
     */
    private static function sortRequire(array $require): array
    {
        $group = static fn(string $package): int => match (true) {
            $package === 'php' => 0,
            str_starts_with($package, 'php-') => 1,
            str_starts_with($package, 'ext-') => 2,
            str_starts_with($package, 'lib-') => 3,
            default => 4,
        };
        uksort($require, static function (int|string $a, int|string $b) use ($group): int {
            $a = (string) $a;
            $b = (string) $b;

            return [$group($a), $a] <=> [$group($b), $b];
        });

        return $require;
    }

    /**
     * Twig templates that call Slim's path_for( or base_url(.
     *
     * @return list<string>
     */
    private static function twigManual(string $appPath): array
    {
        $manual = [];
        foreach (self::files($appPath, 'twig') as $file) {
            $text = (string) file_get_contents($appPath . '/' . $file);
            $count = substr_count($text, 'path_for(') + substr_count($text, 'base_url(');
            if ($count > 0) {
                $manual[] = sprintf('MANUAL: %s: %d call(s) of path_for( or base_url(: %s (base_url is fine when it is the app\'s own global).', $file, $count, self::TWIG_NOTE);
            }
        }

        return $manual;
    }

    /**
     * Code that reads Slim 3's built-in request, response or environment
     * entries from the container; Slim 4's container has none.
     *
     * @param array<string, string> $sources
     * @param array<string, string> $after
     *
     * @return list<string>
     */
    private static function containerReadManual(array $sources, array $after): array
    {
        $pattern = '/(?:\$(?:c|container)\b|->container\b|getContainer\(\))\s*'
            . '(?:\[\s*[\'"](?:request|response|environment)[\'"]\s*\]'
            . '|->(?:request|response|environment)\b(?!\s*\()'
            . '|->get\(\s*[\'"](?:request|response|environment)[\'"]\s*\))/';
        $manual = [];
        foreach ($sources as $file => $source) {
            $count = preg_match_all($pattern, $after[$file] ?? $source);
            if ($count > 0) {
                $manual[] = sprintf(
                    "MANUAL: %s: %d read(s) of the container's request, response or environment entry; Slim 4's container has none,"
                    . ' so register a factory for it (request: ServerRequestCreatorFactory::create()->createServerRequestFromGlobals()) or use the route\'s own $request and $response.',
                    $file,
                    $count,
                );
            }
        }

        return $manual;
    }

    /**
     * A rewriter's MANUAL lines with the file named after the prefix.
     *
     * @param list<string> $lines
     *
     * @return list<string>
     */
    private static function fileManual(array $lines, string $file): array
    {
        return array_map(
            static fn(string $line): string => str_starts_with($line, 'MANUAL: ')
                ? 'MANUAL: ' . $file . ': ' . substr($line, strlen('MANUAL: '))
                : 'MANUAL: ' . $file . ': ' . $line,
            $lines,
        );
    }

    /** "Did X." becomes "Did X in FILE." (with "(N times)" when it happened more than once). */
    private static function inFile(string $line, string $file, int $count): string
    {
        return rtrim($line, '.') . ' in ' . $file . ($count > 1 ? sprintf(' (%d times)', $count) : '') . '.';
    }

    /** A change line in its dry-run form. */
    private static function would(string $line): string
    {
        $space = strpos($line, ' ');
        $first = $space === false ? $line : substr($line, 0, $space);
        $rest = $space === false ? '' : substr($line, $space);

        return 'Dry run: would ' . (self::WOULD[$first] ?? lcfirst($first)) . $rest;
    }

    /**
     * @param list<string> $needles
     */
    private static function containsAny(string $text, array $needles): bool
    {
        foreach ($needles as $needle) {
            if (str_contains($text, $needle)) {
                return true;
            }
        }

        return false;
    }

    /**
     * Every file with the extension under the app, relative and sorted,
     * outside the folders in SKIP_DIRS.
     *
     * @return list<string>
     */
    private static function files(string $appPath, string $extension): array
    {
        $found = [];
        $stack = [$appPath];
        while (($dir = array_pop($stack)) !== null) {
            $handle = @opendir($dir);
            if ($handle === false) {
                continue;
            }
            while (($entry = readdir($handle)) !== false) {
                if ($entry === '.' || $entry === '..') {
                    continue;
                }
                $full = $dir . '/' . $entry;
                if (is_link($full)) {
                    continue;
                }
                if (is_dir($full)) {
                    if (!in_array(strtolower($entry), self::SKIP_DIRS, true)) {
                        $stack[] = $full;
                    }
                    continue;
                }
                if (strtolower(pathinfo($entry, PATHINFO_EXTENSION)) === $extension) {
                    $found[] = substr($full, strlen($appPath) + 1);
                }
            }
            closedir($handle);
        }
        sort($found);

        return $found;
    }

    private static function write(string $file, string $content): void
    {
        $dir = dirname($file);
        if (!is_dir($dir) && !mkdir($dir, 0775, true) && !is_dir($dir)) {
            throw new ToolError(sprintf('Could not create "%s".', $dir));
        }
        if (file_put_contents($file, $content) === false) {
            throw new ToolError(sprintf('Could not write "%s".', $file));
        }
    }
}
