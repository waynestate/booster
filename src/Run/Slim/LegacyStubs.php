<?php

declare(strict_types=1);

namespace Waynestate\Booster\Run\Slim;

/**
 * The three small PHP files the `slim-3-to-4` hop copies into a Slim 3 app so
 * its bootstrap runs on Slim 4 with the fewest edits: a container that still
 * answers `$c['x']`, `$c->x` and `$c->get('x')`, an adapter that runs a Slim 3
 * double-pass middleware as PSR-15, and the app factory glue that turns Slim 3
 * settings into Slim 4 middleware. They are copied into the app (no runtime
 * dependency on Booster), so each one is a complete file.
 *
 * Slim 3 to 4 is the sequel where the container walked out of the band and
 * started a solo career. These stubs are the reunion tour.
 */
final class LegacyStubs
{
    private const HEADER = <<<'PHP'
        <?php

        /*
         * Generated by Booster for the Slim 3 to 4 move; delete when no longer needed.
         * https://booster.apps.wayne.edu/
         */

        declare(strict_types=1);

        namespace {{namespace}};


        PHP;

    private const CONTAINER = <<<'PHP'
        /**
         * Slim 3's container on Slim 4: the app's Pimple container, readable the three
         * ways Slim 3 allowed ($c['x'], $c->x and $c->get('x')), handed to
         * AppFactory::setContainer() so no factory file has to change.
         */
        final class LegacyContainer extends \Pimple\Container implements \Psr\Container\ContainerInterface
        {
            /**
             * @param string $id
             */
            public function get($id): mixed
            {
                if (!$this->offsetExists($id)) {
                    throw new LegacyNotFound(sprintf('Identifier "%s" is not defined in the container.', $id));
                }

                return $this[$id];
            }

            /**
             * @param string $id
             */
            public function has($id): bool
            {
                return $this->offsetExists($id);
            }

            public function __get(string $name): mixed
            {
                return $this[$name];
            }

            public function __isset(string $name): bool
            {
                return $this->offsetExists($name);
            }
        }

        /**
         * Thrown by LegacyContainer::get() for an id the container does not hold.
         */
        final class LegacyNotFound extends \RuntimeException implements \Psr\Container\NotFoundExceptionInterface {}

        PHP;

    private const DOUBLE_PASS = <<<'PHP'
        /**
         * Runs a Slim 3 double-pass middleware, __invoke($request, $response, $next),
         * as a PSR-15 middleware on Slim 4. The middleware gets a fresh response and a
         * $next that reaches the rest of the stack. Headers it set on the response it
         * passes to $next are copied onto the inner answer (without replacing a header
         * the inner layers set), as Slim 3 kept them. A response it returns without
         * calling $next is returned as is. A middleware that is already PSR-15 (a
         * companion package on its Slim 4 line) is run as it is.
         */
        final class LegacyDoublePass implements \Psr\Http\Server\MiddlewareInterface
        {
            /** @var callable|\Psr\Http\Server\MiddlewareInterface */
            private $legacy;

            public function __construct(callable|\Psr\Http\Server\MiddlewareInterface $legacy)
            {
                $this->legacy = $legacy;
            }

            public function process(
                \Psr\Http\Message\ServerRequestInterface $request,
                \Psr\Http\Server\RequestHandlerInterface $handler,
            ): \Psr\Http\Message\ResponseInterface {
                if ($this->legacy instanceof \Psr\Http\Server\MiddlewareInterface) {
                    return $this->legacy->process($request, $handler);
                }

                $response = new \Slim\Psr7\Response();
                $next = static function (
                    \Psr\Http\Message\ServerRequestInterface $req,
                    \Psr\Http\Message\ResponseInterface $res,
                ) use ($handler): \Psr\Http\Message\ResponseInterface {
                    $answer = $handler->handle($req);
                    foreach ($res->getHeaders() as $name => $values) {
                        if (!$answer->hasHeader((string) $name)) {
                            $answer = $answer->withHeader((string) $name, $values);
                        }
                    }

                    return $answer;
                };

                return ($this->legacy)($request, $response, $next);
            }
        }

        PHP;

    private const APP = <<<'PHP'
        /**
         * Builds a Slim 4 app the way the Slim 3 app was built, and adds what Slim 3
         * did by itself. Call create() where the app did `new \Slim\App(...)`, and
         * finish() just before run(), after the app's own middleware.
         */
        final class LegacyApp
        {
            /** Slim 3's settings defaults: a setting the app never set still meant this. */
            private const SLIM3_DEFAULTS = [
                'httpVersion' => '1.1',
                'responseChunkSize' => 4096,
                'outputBuffering' => 'append',
                'determineRouteBeforeAppMiddleware' => false,
                'displayErrorDetails' => false,
                'addContentLengthHeader' => true,
                'routerCacheFile' => false,
            ];

            /**
             * @param array<string, mixed> $config Slim 3's container values, e.g. ['settings' => [...]]
             */
            public static function create(array $config = []): \Slim\App
            {
                $settings = $config['settings'] ?? [];
                if (is_array($settings)) {
                    $config['settings'] = array_merge(self::SLIM3_DEFAULTS, $settings);
                }

                $container = new LegacyContainer($config);
                \Slim\Factory\AppFactory::setContainer($container);

                return \Slim\Factory\AppFactory::create();
            }

            /**
             * Slim 4 runs the last added middleware first, so the error middleware,
             * added last, is outermost, and routing runs before the app's middleware.
             */
            public static function finish(\Slim\App $app): \Slim\App
            {
                $settings = [];
                $container = $app->getContainer();
                if ($container instanceof \ArrayAccess && isset($container['settings']) && is_array($container['settings'])) {
                    $settings = $container['settings'];
                }
                $settings = array_merge(self::SLIM3_DEFAULTS, $settings);

                $cacheFile = $settings['routerCacheFile'];
                if (is_string($cacheFile) && $cacheFile !== '') {
                    $app->getRouteCollector()->setCacheFile($cacheFile);
                }

                $buffering = $settings['outputBuffering'];
                if ($buffering === 'append' || $buffering === 'prepend') {
                    $app->add(new \Slim\Middleware\OutputBufferingMiddleware(
                        new \Slim\Psr7\Factory\StreamFactory(),
                        $buffering === 'prepend'
                            ? \Slim\Middleware\OutputBufferingMiddleware::PREPEND
                            : \Slim\Middleware\OutputBufferingMiddleware::APPEND,
                    ));
                }

                // Outside output buffering, so the length counts echoed output, as Slim 3's did.
                if ($settings['addContentLengthHeader'] === true) {
                    $app->add(new \Slim\Middleware\ContentLengthMiddleware());
                }

                $app->addBodyParsingMiddleware();
                $app->addRoutingMiddleware();
                $app->addErrorMiddleware((bool) $settings['displayErrorDetails'], true, true);

                return $app;
            }
        }

        PHP;

    /** LegacyContainer and LegacyNotFound. */
    public static function container(string $namespace): string
    {
        return self::file($namespace, self::CONTAINER);
    }

    /** LegacyDoublePass. */
    public static function doublePass(string $namespace): string
    {
        return self::file($namespace, self::DOUBLE_PASS);
    }

    /** LegacyApp (needs LegacyContainer in the same namespace). */
    public static function app(string $namespace): string
    {
        return self::file($namespace, self::APP);
    }

    private static function file(string $namespace, string $body): string
    {
        return str_replace('{{namespace}}', trim($namespace, '\\'), self::HEADER) . $body;
    }
}
