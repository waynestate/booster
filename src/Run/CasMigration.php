<?php

declare(strict_types=1);

namespace Waynestate\Booster\Run;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Waynestate\Booster\ToolError;

/**
 * Moves an app off cit-web-infra/wayne-cas where Rector cannot reach: the
 * published CAS config, the web middleware wiring, the auth guard and
 * provider, and the user model's trait usage. It never runs app code; the
 * old files are read with conservative patterns, and anything it cannot move
 * safely becomes a manual note that names the file.
 */
final class CasMigration
{
    public const OLD_CONFIG = 'config/wayne-cas.php';
    public const NEW_CONFIG = 'config/sesame.php';

    public const KERNEL = 'app/Http/Kernel.php';
    public const ROUTE_PROVIDER = 'app/Providers/RouteServiceProvider.php';
    public const AUTH_CONFIG = 'config/auth.php';

    public const INTERFACE = 'WayneCasable';
    public const READ_ONLY_TRAIT = 'ReadOnlyAttributes';
    public const CAS_ALIAS = 'wayne.cas';

    private const OLD_NAMESPACE = 'WSU\WayneCas';
    private const NEW_NAMESPACE = 'Waynestate\Sesame\WayneCas';
    private const NEW_AUTHENTICATE_FQN = '\Waynestate\Sesame\WayneCas\WayneAuthenticate';

    // The one line of a RouteServiceProvider that loads the web routes under
    // the web middleware, in every spacing shape Booster will rewrite.
    private const WEB_ROUTES_PATTERN = '/Route::middleware\(([ \t]*\x27web\x27[ \t]*)\)([ \t\n\r]*->[ \t]*group[ \t]*\([ \t]*base_path[ \t]*\([ \t]*\x27routes\/web\.php\x27[ \t]*\)[ \t]*\))/';

    // Fully qualified forms as they appear in source, leading backslash included.
    private const INTERFACE_FQN = '\Waynestate\Sesame\WayneCas\WayneCasable';
    private const OLD_INTERFACE_FQN = '\WSU\WayneCas\WayneCasable';
    private const READ_ONLY_FQN = '\Waynestate\Sesame\WayneCas\ReadOnlyAttributes';
    private const OLD_READ_ONLY_FQN = '\WSU\WayneCas\ReadOnlyAttributes';

    private const GENERATED_HEADER = "/*\n * Generated by Booster from config/wayne-cas.php. The old file stays\n * in place and can be removed once SESAME is verified.\n */";

    public function migrate(string $appPath, bool $dryRun): CasMigrationResult
    {
        $appPath = str_replace('\\', '/', rtrim($appPath, '/\\'));
        $changes = [];
        $files = [];
        $manual = [];

        $root = $this->oldConfig($appPath, $manual);
        if ($root !== null) {
            $newFile = $appPath . '/' . self::NEW_CONFIG;
            if (!is_file($newFile)) {
                $template = $this->sesameTemplate($appPath);
                if ($template === null) {
                    $manual[] = self::NEW_CONFIG . ': BOOSTER has no SESAME config to base it on (no vendor/waynestate/sesame and no bundled copy), so it wrote nothing. Copy SESAME\'s config/sesame.php into the app and set its cas.base_url to \'' . $root . '\'.';
                } elseif ($this->writeSesameConfig($newFile, $template[0], $root, $dryRun, $manual)) {
                    $changes[] = ($dryRun ? 'Dry run: would write ' : '') . self::NEW_CONFIG . sprintf(' from %s, with cas.base_url falling back to \'%s\' from %s and user_resolver defaulting to the compat resolver.', $template[1], $root, self::OLD_CONFIG);
                    $files[] = ['file' => self::NEW_CONFIG, 'diff' => 'SESAME config with the old root fallback and the compat resolver'];
                }
            } else {
                $manual[] = self::NEW_CONFIG . ' already exists, so BOOSTER left it alone. Set its cas.base_url to \'' . $root . '\' (the old wayne-cas root) if it differs.';
            }
        }

        $this->middleware($appPath, $dryRun, $manual, $changes, $files);
        $this->authConfig($appPath, $dryRun, $manual, $changes, $files);

        $finals = [];
        foreach ($this->modelFiles($appPath) as $relative => $absolute) {
            $original = (string) file_get_contents($absolute);
            $rewrite = $this->rewriteModel($original, $relative, $manual);
            $finals[$relative] = $rewrite === null ? $original : $rewrite['content'];
            if ($rewrite === null) {
                continue;
            }
            if (!$dryRun) {
                file_put_contents($absolute, $rewrite['content']);
            }
            // The report must match the diff: name each thing the rewrite adds.
            $clauses = ['rewritten to implements ' . self::INTERFACE_FQN];
            if ($rewrite['added_trait']) {
                $clauses[] = 'uses ' . self::READ_ONLY_FQN;
            }
            if ($rewrite['signature_fixed']) {
                $clauses[] = 'getReadOnlyAttributes() now matches the compat interface';
            }
            if ($rewrite['import_removed']) {
                $clauses[] = 'the wayne-cas import was removed';
            }
            $changes[] = ($dryRun ? 'Dry run: would rewrite ' : '') . $relative . ': ' . implode('; ', $clauses) . '.';
            $diff = ['implements ' . self::INTERFACE_FQN];
            if ($rewrite['added_trait']) {
                $diff[] = 'uses ' . self::READ_ONLY_FQN;
            }
            if ($rewrite['signature_fixed']) {
                $diff[] = 'signature fixed';
            }
            if ($rewrite['import_removed']) {
                $diff[] = 'import removed';
            }
            $files[] = ['file' => $relative, 'diff' => implode('; ', $diff)];
        }

        // A file that still carries WayneCasable in a trait use line failed the
        // step, so name it; the gate then keeps the hop from reporting success.
        $failures = [];
        foreach ($finals as $relative => $content) {
            if (self::traitStillUsesInterface($content)) {
                $failures[] = $relative;
                $manual[] = $relative . ': BOOSTER left ' . self::INTERFACE . ' in a trait use line, so this file failed the step. Move it to implements ' . self::INTERFACE_FQN . ' plus use ' . self::READ_ONLY_FQN . ' by hand.';
            }
        }

        return new CasMigrationResult($changes, $files, $manual, $failures);
    }

    /**
     * Reads the published wayne-cas config without running it. Returns the
     * plain-string root, or null when Booster cannot read one.
     *
     * @param list<string> $manual
     */
    private function oldConfig(string $appPath, array &$manual): ?string
    {
        $file = $appPath . '/' . self::OLD_CONFIG;
        if (!is_file($file)) {
            $manual[] = self::OLD_CONFIG . ' is missing, so BOOSTER has no CAS root to move. Write ' . self::NEW_CONFIG . ' with sesame.cas.base_url set to your CAS server.';

            return null;
        }

        $content = (string) file_get_contents($file);
        $root = self::plainString($content, 'root');
        if ($root === null) {
            $manual[] = self::OLD_CONFIG . ': BOOSTER could not read a plain string for \'root\', so it left ' . self::NEW_CONFIG . ' alone. Set sesame.cas.base_url by hand.';
        }
        if (self::boolValue($content, 'use2FA') === true) {
            $manual[] = 'MANUAL: the app had use2FA enabled in ' . self::OLD_CONFIG . ', but SESAME does not carry Duo. Re-enable two-factor in the app itself; DUO_HOSTNAME, DUO_IKEY, DUO_SKEY and DUO_AKEY do nothing under SESAME.';
        }
        $manual[] = self::OLD_CONFIG . ': left in place; remove it once SESAME is verified.';

        return $root;
    }

    /**
     * A quoted string value for a key, straight from the source text.
     */
    private static function plainString(string $content, string $key): ?string
    {
        if (preg_match('/^[ \t]*\x27' . $key . '\x27[ \t]*=>[ \t]*\x27([^\x27]*)\x27/m', $content, $m) === 1) {
            return $m[1];
        }
        if (preg_match('/^[ \t]*\x27' . $key . '\x27[ \t]*=>[ \t]*"([^"]*)"/m', $content, $m) === 1) {
            return $m[1];
        }

        return null;
    }

    /**
     * A boolean value for a key, straight from the source text.
     */
    private static function boolValue(string $content, string $key): ?bool
    {
        if (preg_match('/^[ \t]*\x27' . $key . '\x27[ \t]*=>[ \t]*true\b/m', $content) === 1) {
            return true;
        }
        if (preg_match('/^[ \t]*\x27' . $key . '\x27[ \t]*=>[ \t]*false\b/m', $content) === 1) {
            return false;
        }

        return null;
    }

    /**
     * The published SESAME config Booster bases the new config/sesame.php on:
     * the app's own vendor copy when present, otherwise the copy Booster ships.
     *
     * @return array{0: string, 1: string}|null the content and a label naming the source
     */
    private function sesameTemplate(string $appPath): ?array
    {
        $vendor = $appPath . '/vendor/waynestate/sesame/config/sesame.php';
        if (is_file($vendor)) {
            $content = @file_get_contents($vendor);
            if ($content !== false) {
                return [$content, 'the app\'s vendor/waynestate/sesame config'];
            }
        }
        $bundled = dirname(__DIR__, 2) . '/resources/sesame/config/sesame.php';
        $content = @file_get_contents($bundled);
        if ($content === false) {
            return null;
        }

        return [$content, 'Booster\'s bundled SESAME 0.2.2 config'];
    }

    /**
     * Writes config/sesame.php: the published SESAME config under the existing
     * header comment, with exactly two lines changed. cas.base_url falls back
     * to the old wayne-cas root, and user_resolver defaults to the compat
     * resolver. Returns false, with a manual note, when the published config
     * lacks the exact lines it must change, so Booster never writes a partial
     * config.
     *
     * @param list<string> $manual
     */
    private function writeSesameConfig(string $file, string $template, string $root, bool $dryRun, array &$manual): bool
    {
        $baseLine = "'base_url' => Setting::get('SESAME_CAS_BASE_URL'),";
        $resolverLine = "'user_resolver' => env('SESAME_USER_RESOLVER'),";
        if (substr_count($template, $baseLine) !== 1 || substr_count($template, $resolverLine) !== 1) {
            $manual[] = self::NEW_CONFIG . ': BOOSTER could not find the exact base_url and user_resolver lines in SESAME\'s published config, so it wrote nothing. Copy SESAME\'s config/sesame.php into the app and set cas.base_url to \'' . $root . '\' and user_resolver to \Waynestate\Sesame\WayneCas\UserResolver by hand.';

            return false;
        }
        $escaped = str_replace(['\\', "'"], ['\\\\', "\\'"], $root);
        $body = preg_replace('/^<\?php[ \t]*\r?\n/', '', $template, 1);
        $php = "<?php\n\n" . self::GENERATED_HEADER . "\n" . $body;
        $php = str_replace($baseLine, sprintf("'base_url' => Setting::get('SESAME_CAS_BASE_URL') ?? '%s',", $escaped), $php);
        $php = str_replace($resolverLine, "'user_resolver' => env('SESAME_USER_RESOLVER', \\Waynestate\\Sesame\\WayneCas\\UserResolver::class),", $php);
        if (!$dryRun) {
            $dir = dirname($file);
            if (!is_dir($dir) && !mkdir($dir, 0775, true) && !is_dir($dir)) {
                throw new ToolError(sprintf('Could not create "%s".', $dir));
            }
            if (file_put_contents($file, $php) === false) {
                throw new ToolError(sprintf('Could not write "%s".', $file));
            }
        }

        return true;
    }

    /**
     * Moves the CAS middleware off the global web group and onto the app's
     * own web routes: the web group loses its WayneAuthenticate entry (class
     * reference, short name or wayne.cas alias), the wayne.cas alias is set
     * against SESAME's class in $routeMiddleware or $middlewareAliases, and
     * the web route registration gains the alias. The move is all-or-nothing:
     * if any piece cannot be found exactly, nothing is touched and a manual
     * note names the file.
     *
     * @param list<string> $manual
     * @param list<string> $changes
     * @param list<array{file: string, diff: string}> $files
     */
    private function middleware(string $appPath, bool $dryRun, array &$manual, array &$changes, array &$files): void
    {
        $kernelFile = $appPath . '/' . self::KERNEL;
        if (!is_file($kernelFile)) {
            return;
        }
        $kernel = (string) file_get_contents($kernelFile);
        $group = self::webMiddlewareGroup($kernel);
        if ($group === null) {
            return;
        }
        [$groupStart, $groupClose] = $group;
        $entries = self::casEntries($kernel, $groupStart, $groupClose);
        if ($entries === null || $entries === []) {
            if ($entries === null) {
                $manual[] = self::KERNEL . ': BOOSTER found the wayne.cas middleware mixed with other entries on one line of the web middleware group, so it left the file alone. Move the middleware by hand.';
            }

            return;
        }

        $alias = self::aliasRegistration($kernel);
        if ($alias === null) {
            $manual[] = self::KERNEL . ': BOOSTER found no $routeMiddleware or $middlewareAliases to register the wayne.cas alias in, so it left the middleware where it is. Register the alias by hand.';

            return;
        }
        [$property, $propStart, $propClose, $valueSpan] = $alias;

        $providerFile = $appPath . '/' . self::ROUTE_PROVIDER;
        if (!is_file($providerFile)) {
            $manual[] = self::ROUTE_PROVIDER . ' is missing, so BOOSTER left ' . self::KERNEL . ' alone. Remove wayne.cas from the web middleware group and add it to the web routes by hand.';

            return;
        }
        $provider = (string) file_get_contents($providerFile);
        if (preg_match_all(self::WEB_ROUTES_PATTERN, $provider) !== 1) {
            $manual[] = self::ROUTE_PROVIDER . ": BOOSTER could not find Route::middleware('web') loading routes/web.php, so it left the middleware where it is. Add the wayne.cas middleware to the web routes by hand.";

            return;
        }

        $ops = [];
        foreach ($entries as [$lineStart, $lineEnd]) {
            $end = $lineEnd < strlen($kernel) && $kernel[$lineEnd] === "\n" ? $lineEnd + 1 : $lineEnd;
            $ops[] = [$lineStart, $end, ''];
        }
        $aliasAdded = false;
        $aliasChanged = false;
        if ($valueSpan !== null) {
            [$valueStart, $valueEnd] = $valueSpan;
            if (substr($kernel, $valueStart, $valueEnd - $valueStart) !== self::NEW_AUTHENTICATE_FQN . '::class') {
                $ops[] = [$valueStart, $valueEnd, self::NEW_AUTHENTICATE_FQN . '::class'];
                $aliasChanged = true;
            }
        } else {
            [$insertAt, $entryIndent] = self::entryInsertion($kernel, $propStart, $propClose);
            $ops[] = [$insertAt, $insertAt, $entryIndent . "'" . self::CAS_ALIAS . "' => " . self::NEW_AUTHENTICATE_FQN . "::class," . "\n"];
            $aliasAdded = true;
        }

        $newKernel = self::applyEdits($kernel, $ops);
        $newProvider = preg_replace_callback(
            self::WEB_ROUTES_PATTERN,
            static fn(array $m): string => "Route::middleware(['web', '" . self::CAS_ALIAS . "'])" . substr($m[0], strlen('Route::middleware') + strlen($m[1]) + 2),
            $provider,
            1,
        );
        if (!$dryRun) {
            file_put_contents($kernelFile, $newKernel);
            file_put_contents($providerFile, $newProvider);
        }

        $clauses = ['the web middleware group no longer carries ' . self::CAS_ALIAS];
        $diffClauses = ['web group loses ' . self::CAS_ALIAS];
        if ($aliasAdded) {
            $clauses[] = 'the ' . self::CAS_ALIAS . ' alias was added to ' . $property . ' pointing at ' . self::NEW_AUTHENTICATE_FQN . '::class';
            $diffClauses[] = 'alias added to ' . $property;
        } elseif ($aliasChanged) {
            $clauses[] = 'the ' . self::CAS_ALIAS . ' alias now points at ' . self::NEW_AUTHENTICATE_FQN . '::class';
            $diffClauses[] = 'alias points at ' . self::NEW_AUTHENTICATE_FQN . '::class';
        }
        $changes[] = ($dryRun ? 'Dry run: would rewrite ' : '') . self::KERNEL . ': ' . implode('; ', $clauses) . '.';
        $files[] = ['file' => self::KERNEL, 'diff' => implode('; ', $diffClauses)];
        $changes[] = ($dryRun ? 'Dry run: would rewrite ' : '') . self::ROUTE_PROVIDER . ': the web routes now load under the ' . self::CAS_ALIAS . ' middleware.';
        $files[] = ['file' => self::ROUTE_PROVIDER, 'diff' => 'web routes gain the ' . self::CAS_ALIAS . ' middleware'];
    }

    /**
     * Points the web guard at SESAME and the users provider at eloquent:
     * guards.web.driver becomes sesame (it was session), providers.users.driver
     * becomes eloquent (it was wayneCas), and the users provider gains a model
     * key when it has none. Parts already migrated are left alone; anything
     * structural Booster cannot read exactly is left untouched with a manual
     * note that names the file.
     *
     * @param list<string> $manual
     * @param list<string> $changes
     * @param list<array{file: string, diff: string}> $files
     */
    private function authConfig(string $appPath, bool $dryRun, array &$manual, array &$changes, array &$files): void
    {
        $file = $appPath . '/' . self::AUTH_CONFIG;
        if (!is_file($file)) {
            return;
        }
        $content = (string) file_get_contents($file);

        $guards = self::section($content, 'guards');
        if ($guards === null) {
            $manual[] = self::AUTH_CONFIG . ': BOOSTER could not read the guards section, so it left the file alone. Point the web guard at the sesame driver by hand.';

            return;
        }
        $web = self::entry($content, $guards[0], $guards[1], 'web');
        if ($web === null) {
            $manual[] = self::AUTH_CONFIG . ': BOOSTER could not find the web guard, so it left the file alone. Point it at the sesame driver by hand.';

            return;
        }
        $guardDriver = self::driverValue($content, $web[0], $web[1]);
        if ($guardDriver === null) {
            $manual[] = self::AUTH_CONFIG . ": BOOSTER could not read a plain driver for the web guard, so it left the file alone. Set its driver to 'sesame' by hand.";

            return;
        }
        [$guardDriverText, $guardDriverStart, $guardDriverEnd] = $guardDriver;

        $providers = self::section($content, 'providers');
        if ($providers === null) {
            $manual[] = self::AUTH_CONFIG . ': BOOSTER could not read the providers section, so it left the file alone. Point the users provider at the eloquent driver by hand.';

            return;
        }
        $users = self::entry($content, $providers[0], $providers[1], 'users');
        if ($users === null) {
            $manual[] = self::AUTH_CONFIG . ': BOOSTER could not find the users provider, so it left the file alone. Point it at the eloquent driver by hand.';

            return;
        }
        $providerDriver = self::driverValue($content, $users[0], $users[1]);
        if ($providerDriver === null) {
            $manual[] = self::AUTH_CONFIG . ": BOOSTER could not read a plain driver for the users provider, so it left the file alone. Set its driver to 'eloquent' by hand.";

            return;
        }
        [$providerDriverText, $providerDriverStart, $providerDriverEnd] = $providerDriver;

        $ops = [];
        $clauses = [];
        $diffClauses = [];

        if ($guardDriverText === 'session') {
            $ops[] = [$guardDriverStart, $guardDriverEnd, 'sesame'];
            $clauses[] = 'the web guard now uses the sesame driver';
            $diffClauses[] = 'web guard driver session to sesame';
        } elseif ($guardDriverText !== 'sesame') {
            $manual[] = self::AUTH_CONFIG . ": BOOSTER found the web guard on the {$guardDriverText} driver, which it does not change. Point it at the sesame driver by hand.";
        }

        $modelFqn = is_file($appPath . '/app/Models/User.php') ? 'App\Models\User' : 'App\User';
        if ($providerDriverText === 'wayneCas') {
            $ops[] = [$providerDriverStart, $providerDriverEnd, 'eloquent'];
            $clauses[] = 'the users provider now uses the eloquent driver';
            $diffClauses[] = 'users provider driver wayneCas to eloquent';
        } elseif ($providerDriverText !== 'eloquent') {
            $manual[] = self::AUTH_CONFIG . ": BOOSTER found the users provider on the {$providerDriverText} driver, which it does not change. Point it at the eloquent driver by hand.";
        }

        if (in_array($providerDriverText, ['wayneCas', 'eloquent'], true) && !self::modelKey($content, $users[0], $users[1])) {
            if (substr_count(substr($content, $users[0], $users[1] - $users[0]), "\n") === 0) {
                $manual[] = self::AUTH_CONFIG . ': BOOSTER found the users provider on one line, so it could not add a model key. Add the model key by hand.';
            } else {
                [$insertAt, $indent] = self::entryInsertion($content, $users[0], $users[1]);
                $ops[] = [$insertAt, $insertAt, $indent . "'model' => " . $modelFqn . "::class," . "\n"];
                $clauses[] = 'the users provider got a model key pointing at ' . $modelFqn . '::class';
                $diffClauses[] = 'model key added to the users provider';
            }
        }

        if ($ops === []) {
            return;
        }

        $newContent = self::applyEdits($content, $ops);
        if (!$dryRun) {
            file_put_contents($file, $newContent);
        }
        $changes[] = ($dryRun ? 'Dry run: would rewrite ' : '') . self::AUTH_CONFIG . ': ' . implode('; ', $clauses) . '.';
        $files[] = ['file' => self::AUTH_CONFIG, 'diff' => implode('; ', $diffClauses)];
    }

    /**
     * The inner span of a top-level 'key' => [...] section: offsets after the
     * opening bracket up to the closing bracket itself. Null when the section
     * is not readable. Either quote style is accepted.
     *
     * @return array{0: int, 1: int}|null
     */
    private static function section(string $content, string $key): ?array
    {
        if (preg_match('/^[ \t]*([\x27"])' . $key . '\1[ \t]*=>[ \t]*\[/m', $content, $m, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        return self::bracketSpan($content, $m[0][1] + strlen($m[0][0]) - 1);
    }

    /**
     * The inner span of a 'name' => [...] entry inside [outerStart,
     * outerClose]. Null when the entry is not readable. Either quote style is
     * accepted.
     *
     * @return array{0: int, 1: int}|null
     */
    private static function entry(string $content, int $outerStart, int $outerClose, string $name): ?array
    {
        $inner = substr($content, $outerStart, $outerClose - $outerStart);
        if (preg_match('/^[ \t]*([\x27"])' . $name . '\1[ \t]*=>[ \t]*\[/m', $inner, $m, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        return self::bracketSpan($content, $outerStart + $m[0][1] + strlen($m[0][0]) - 1);
    }

    /**
     * The quoted value of the driver key inside [start, close]: the text and
     * the offsets of the value alone, quotes excluded. Null when there is no
     * plain quoted driver string.
     *
     * @return array{0: string, 1: int, 2: int}|null
     */
    private static function driverValue(string $content, int $start, int $close): ?array
    {
        $inner = substr($content, $start, $close - $start);
        if (preg_match('/^[ \t]*([\x27"])driver\1[ \t]*=>[ \t]*[\x27"]([^"\x27]*)[\x27"]/m', $inner, $m, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }
        $valueOffset = $start + $m[2][1];

        return [$m[2][0], $valueOffset, $valueOffset + strlen($m[2][0])];
    }

    /**
     * Whether the entry inside [start, close] already carries a model key.
     */
    private static function modelKey(string $content, int $start, int $close): bool
    {
        $inner = substr($content, $start, $close - $start);

        return preg_match('/^[ \t]*([\x27"])model\1[ \t]*=>/m', $inner) === 1;
    }

    /**
     * Where a new entry goes before a closing bracket at [innerStart, close]:
     * the start of the bracket's own line and the indentation a sibling entry
     * would carry.
     *
     * @return array{0: int, 1: string}
     */
    private static function entryInsertion(string $content, int $innerStart, int $close): array
    {
        $closeLineStart = strrpos(substr($content, 0, $close), "\n");
        $closeLineStart = $closeLineStart === false ? 0 : $closeLineStart + 1;
        $indent = '';
        foreach (self::lines(substr($content, $innerStart, $close - $innerStart)) as [$offset, $text]) {
            $trimmed = trim($text);
            if ($trimmed !== '' && !str_starts_with($trimmed, '//') && !str_starts_with($trimmed, '#')) {
                $indent = substr($text, 0, strlen($text) - strlen(ltrim($text, " \t")));

                break;
            }
        }
        if ($indent === '') {
            $closeLine = substr($content, $closeLineStart, $close - $closeLineStart);
            $indent = substr($closeLine, 0, strlen($closeLine) - strlen(ltrim($closeLine, " \t"))) . '    ';
        }

        return [$closeLineStart, $indent];
    }

    /**
     * The inner span of the 'web' entry of $middlewareGroups: offsets after
     * the group's opening bracket up to its closing bracket. Null when the
     * Kernel has no readable web group.
     *
     * @return array{0: int, 1: int}|null
     */
    private static function webMiddlewareGroup(string $content): ?array
    {
        if (preg_match('/\$middlewareGroups[ \t]*=[ \t]*\[/m', $content, $m, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }
        $groups = self::bracketSpan($content, $m[0][1] + strlen($m[0][0]) - 1);
        if ($groups === null) {
            return null;
        }
        [$groupsStart, $groupsClose] = $groups;
        $inner = substr($content, $groupsStart, $groupsClose - $groupsStart);
        if (preg_match('/\x27web\x27[ \t]*=>[ \t]*\[/m', $inner, $w, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        return self::bracketSpan($content, $groupsStart + $w[0][1] + strlen($w[0][0]) - 1);
    }

    /**
     * Given the offset of an opening bracket, the offsets around the matching
     * close: inner start and the closing bracket itself. Null on unbalanced
     * brackets. Brace matching is naive (it does not skip strings), which is
     * fine for the boilerplate this feeds.
     *
     * @return array{0: int, 1: int}|null
     */
    private static function bracketSpan(string $content, int $open): ?array
    {
        $depth = 0;
        $length = strlen($content);
        for ($i = $open; $i < $length; $i++) {
            if ($content[$i] === '[') {
                $depth++;
            } elseif ($content[$i] === ']') {
                $depth--;
                if ($depth === 0) {
                    return [$open + 1, $i];
                }
            }
        }

        return null;
    }

    /**
     * Every single-entry line inside the group whose entry is the CAS
     * middleware in any form: the wayne.cas alias or a WayneAuthenticate
     * class reference. Line spans exclude the newline. Null when a line mixes
     * the CAS entry with other entries, which Booster refuses to touch.
     *
     * @return list<array{0: int, 1: int}>|null
     */
    private static function casEntries(string $content, int $groupStart, int $groupClose): ?array
    {
        $entries = [];
        foreach (self::lines(substr($content, $groupStart, $groupClose - $groupStart)) as [$offset, $text]) {
            $trimmed = trim($text);
            if ($trimmed === '' || str_starts_with($trimmed, '//') || str_starts_with($trimmed, '#')) {
                continue;
            }
            $single = trim((string) preg_replace('/[ \t]*(?:\/\/|#).*$/', '', rtrim($trimmed, ',')));
            if (strpos($single, ',') !== false) {
                if (self::isCasEntry($single) || str_contains($single, self::CAS_ALIAS) || str_contains($single, 'WayneAuthenticate')) {
                    return null;
                }

                continue;
            }
            if (self::isCasEntry($single)) {
                $entries[] = [$groupStart + $offset, $groupStart + $offset + strlen($text)];
            }
        }

        return $entries;
    }

    /**
     * Whether one trimmed, comma-free array entry is the CAS middleware: the
     * wayne.cas alias or a WayneAuthenticate class reference in any namespace
     * form.
     */
    private static function isCasEntry(string $entry): bool
    {
        if ($entry === "'" . self::CAS_ALIAS . "'" || $entry === '"' . self::CAS_ALIAS . '"') {
            return true;
        }

        return str_ends_with($entry, 'WayneAuthenticate::class');
    }

    /**
     * The alias property that carries wayne.cas and the value span of its
     * entry: [property name, property inner start, closing bracket offset,
     * value offsets or null when the property has no wayne.cas entry]. Null
     * when neither $routeMiddleware nor $middlewareAliases is readable.
     *
     * @return array{0: string, 1: int, 2: int, 3: array{0: int, 1: int}|null}|null
     */
    private static function aliasRegistration(string $content): ?array
    {
        foreach (['$routeMiddleware', '$middlewareAliases'] as $property) {
            // The dollar is escaped for the pattern but kept plain in reports.
            if (preg_match('/' . str_replace('$', '\\$', $property) . '[ \t]*=[ \t]*\[/m', $content, $m, PREG_OFFSET_CAPTURE) !== 1) {
                continue;
            }
            $span = self::bracketSpan($content, $m[0][1] + strlen($m[0][0]) - 1);
            if ($span === null) {
                return null;
            }
            [$start, $close] = $span;
            $value = null;
            foreach (self::lines(substr($content, $start, $close - $start)) as [$offset, $text]) {
                // Either quote style, matched by backreference so the quotes agree.
                if (preg_match('/^[ \t]*([\x27"])wayne\.cas\1[ \t]*=>[ \t]*(.+?)[ \t]*,?[ \t]*$/', $text, $v, PREG_OFFSET_CAPTURE)) {
                    $value = [$start + $offset + $v[2][1], $start + $offset + $v[2][1] + strlen($v[2][0])];

                    break;
                }
            }

            return [$property, $start, $close, $value];
        }

        return null;
    }

    /**
     * Applies non-overlapping [start, end, replacement] edits to the text,
     * highest offset first, so earlier offsets stay valid.
     *
     * @param list<array{0: int, 1: int, 2: string}> $ops
     */
    private static function applyEdits(string $content, array $ops): string
    {
        usort($ops, static fn(array $a, array $b): int => $b[0] <=> $a[0]);
        foreach ($ops as [$start, $end, $replacement]) {
            $content = substr($content, 0, $start) . $replacement . substr($content, $end);
        }

        return $content;
    }

    /**
     * Offset and text of each line, newline exclusive.
     *
     * @return list<array{0: int, 1: string}>
     */
    private static function lines(string $content): array
    {
        $out = [];
        $offset = 0;
        while (($nl = strpos($content, "\n", $offset)) !== false) {
            $out[] = [$offset, substr($content, $offset, $nl - $offset)];
            $offset = $nl + 1;
        }
        $out[] = [$offset, substr($content, $offset)];

        return $out;
    }

    /**
     * PHP files outside vendor/, node_modules/, public/ and storage/.
     *
     * @return array<string, string> relative path to absolute path
     */
    private function modelFiles(string $path): array
    {
        $files = [];
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if (!$file->isFile() || !str_ends_with($file->getFilename(), '.php')) {
                continue;
            }
            $relative = $this->relative($path, $file->getPathname());
            foreach (['.git/', 'vendor/', 'node_modules/', 'public/', 'storage/', 'bootstrap/cache/'] as $skip) {
                if (str_starts_with($relative, $skip)) {
                    continue 2;
                }
            }
            $files[$relative] = $file->getPathname();
        }
        ksort($files);

        return $files;
    }

    /**
     * Rewrites a model that uses WayneCasable as a trait into one that
     * implements it (fully qualified) and uses ReadOnlyAttributes. Handles the
     * trait in every form Rector may leave behind, fixes the known broken
     * getReadOnlyAttributes signature, and tidies the imports. Returns the new
     * content with flags for what the diff actually adds, or null when there is
     * nothing to do or the shape is not safe, in which case a manual note is
     * added.
     *
     * @param list<string> $manual
     *
     * @return array{content: string, added_interface: bool, added_trait: bool, signature_fixed: bool, import_removed: bool}|null
     */
    private function rewriteModel(string $content, string $relative, array &$manual): ?array
    {
        $region = $this->classRegion($content);
        if ($region === null) {
            if (self::referencesTrait($content)) {
                $manual[] = $relative . ': BOOSTER could not find the class that uses ' . self::INTERFACE . ', so it left the file alone. Move the trait to implements ' . self::INTERFACE_FQN . ' plus use ' . self::READ_ONLY_FQN . ' by hand.';
            }

            return null;
        }
        [$classStart, $bracePos] = $region;
        $decl = substr($content, $classStart, $bracePos - $classStart);
        if (str_contains($decl, '{') || preg_match_all('/\b(class|interface|trait|enum)\b/', $decl) !== 1) {
            $manual[] = $relative . ': BOOSTER could not read the class declaration around the ' . self::INTERFACE . ' trait use, so it left the file alone. Move the trait to implements ' . self::INTERFACE_FQN . ' plus use ' . self::READ_ONLY_FQN . ' by hand.';

            return null;
        }

        $head = substr($content, 0, $classStart);
        $body = substr($content, $bracePos);
        $traitLines = self::traitUseLines($body);

        $interfaceCount = 0;
        $hasFqnUse = false;
        foreach ($traitLines as $line) {
            foreach ($line[2] as $item) {
                if (self::isInterfaceItem($item)) {
                    $interfaceCount++;
                    if ($item !== self::INTERFACE) {
                        $hasFqnUse = true;
                    }
                }
            }
        }
        if ($interfaceCount === 0) {
            return null;
        }
        if ($interfaceCount > 1) {
            $manual[] = $relative . ': BOOSTER found ' . $interfaceCount . ' ' . self::INTERFACE . ' trait uses, so it left the file alone. Keep one, move it to implements ' . self::INTERFACE_FQN . ' plus use ' . self::READ_ONLY_FQN . ' by hand.';

            return null;
        }
        // A bare short-name use only identifies WayneCasable through an import;
        // without one, Booster cannot tell which WayneCasable it is. A fully
        // qualified use names it outright, so no import is required.
        if (!$hasFqnUse) {
            $oldImport = 'use ' . self::OLD_NAMESPACE . '\\' . self::INTERFACE . ';';
            $newImport = 'use ' . self::NEW_NAMESPACE . '\\' . self::INTERFACE . ';';
            if (!str_contains($head, $oldImport) && !str_contains($head, $newImport)) {
                $manual[] = $relative . ': BOOSTER found no import for ' . self::INTERFACE . ', so it left the file alone. Add the import and move the trait to implements ' . self::INTERFACE_FQN . ' by hand.';

                return null;
            }
        }

        $roAlreadyUsed = false;
        foreach ($traitLines as $line) {
            foreach ($line[2] as $item) {
                if ($item === self::READ_ONLY_TRAIT || $item === self::READ_ONLY_FQN || $item === self::OLD_READ_ONLY_FQN) {
                    $roAlreadyUsed = true;
                }
            }
        }

        // Trait lines lose the interface and gain ReadOnlyAttributes once.
        $addedTrait = !$roAlreadyUsed;
        $targets = array_values(array_filter($traitLines, static fn(array $line): bool => self::lineHasInterface($line)));
        usort($targets, static fn(array $a, array $b): int => $b[0] <=> $a[0]);
        foreach ($targets as [$offset, $indent, $items]) {
            $kept = [];
            foreach ($items as $item) {
                if (self::isInterfaceItem($item)) {
                    continue;
                }
                if ($item === self::OLD_READ_ONLY_FQN) {
                    $item = self::READ_ONLY_FQN;
                }
                $kept[] = $item;
            }
            if (!$roAlreadyUsed) {
                $kept[] = self::READ_ONLY_FQN;
            }
            $lineStart = strrpos(substr($body, 0, $offset), "\n");
            $lineStart = $lineStart === false ? 0 : $lineStart + 1;
            if ($kept === []) {
                // Drop the whole line, newline included, plus a blank line that
                // follows, so no gap lingers.
                $end = strpos($body, "\n", $offset);
                $cutEnd = $end === false ? strlen($body) : $end + 1;
                if ($cutEnd < strlen($body) && $body[$cutEnd] === "\n") {
                    $cutEnd++;
                }
                $body = substr($body, 0, $lineStart) . substr($body, $cutEnd);
            } else {
                $end = strpos($body, "\n", $offset);
                $end = $end === false ? strlen($body) : $end;
                $body = substr($body, 0, $lineStart) . $indent . 'use ' . implode(', ', $kept) . ';' . substr($body, $end);
            }
        }

        // The compat interface demands a public getReadOnlyAttributes with a
        // default and an array return type; fix the known broken shape.
        $signatureFixed = false;
        $count = 0;
        $fixed = preg_replace(
            '/([ \t]*)(?:protected|private|public)[ \t]+function[ \t]+getReadOnlyAttributes[ \t]*\(\s*\$persistedAttributes\s*\)(\s*:\s*array)?/',
            '$1public function getReadOnlyAttributes($persistedAttributes = []): array',
            $body,
            1,
            $count,
        );
        if ($fixed !== null && $count === 1) {
            $body = $fixed;
            $signatureFixed = true;
        }

        // The class declaration gains (or normalises to) the fully qualified
        // interface. The whitespace between the declaration and the opening
        // brace is kept.
        $newDecl = $decl;
        $addedInterface = false;
        if (preg_match('/\bimplements\b(.+)$/s', $decl, $m, PREG_OFFSET_CAPTURE) === 1) {
            $listText = $m[1][0];
            $separator = strlen($listText) - strlen(ltrim($listText, " \t\n"));
            $listText = substr($listText, $separator);
            $items = array_values(array_filter(array_map('trim', explode(',', $listText)), static fn(string $item): bool => $item !== ''));
            $hasInterface = false;
            $replaced = false;
            foreach ($items as $i => $item) {
                if (self::isInterfaceItem($item)) {
                    $hasInterface = true;
                    if ($item !== self::INTERFACE_FQN) {
                        $items[$i] = self::INTERFACE_FQN;
                        $replaced = true;
                    }
                }
            }
            if (!$hasInterface) {
                $items[] = self::INTERFACE_FQN;
                $replaced = true;
            }
            if ($replaced) {
                $tail = self::trailingWhitespace($listText);
                $newDecl = substr($decl, 0, $m[1][1] + $separator) . implode(', ', $items) . $tail;
                $addedInterface = true;
            }
        } else {
            $tail = self::trailingWhitespace($decl);
            $newDecl = rtrim($decl) . ' implements ' . self::INTERFACE_FQN . $tail;
            $addedInterface = true;
        }

        // Imports last, so they see the final references.
        [$newHead, $importRemoved] = $this->cleanImports($head, $head . $newDecl . $body);

        return [
            'content' => $newHead . $newDecl . $body,
            'added_interface' => $addedInterface,
            'added_trait' => $addedTrait,
            'signature_fixed' => $signatureFixed,
            'import_removed' => $importRemoved,
        ];
    }

    /**
     * Whether a trait-use item is WayneCasable in any of its forms.
     */
    private static function isInterfaceItem(string $item): bool
    {
        return $item === self::INTERFACE
            || $item === self::OLD_INTERFACE_FQN
            || $item === self::INTERFACE_FQN;
    }

    /**
     * @param array{0: int, 1: string, 2: list<string>} $line
     */
    private static function lineHasInterface(array $line): bool
    {
        foreach ($line[2] as $item) {
            if (self::isInterfaceItem($item)) {
                return true;
            }
        }

        return false;
    }

    /**
     * Whether any class body in the text still uses WayneCasable as a trait.
     */
    private static function traitStillUsesInterface(string $content): bool
    {
        foreach (self::classBodies($content) as $body) {
            foreach (self::traitUseLines($body) as $line) {
                if (self::lineHasInterface($line)) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * The substring of every top-level named class body in the text, braces
     * included. Brace matching is naive (it does not skip strings), which is
     * fine for the safety net this feeds.
     *
     * @return list<string>
     */
    private static function classBodies(string $content): array
    {
        $bodies = [];
        $matches = preg_match_all('/^[ \t]*(?:final[ \t]+|abstract[ \t]+)?class[ \t]+[A-Za-z0-9_]+/m', $content, $m, PREG_OFFSET_CAPTURE);
        if ($matches === false || $matches === 0) {
            return $bodies;
        }
        $length = strlen($content);
        foreach ($m[0] as $match) {
            $start = $match[1];
            $brace = strpos($content, '{', $start);
            if ($brace === false) {
                continue;
            }
            $depth = 0;
            $end = $length;
            for ($i = $brace; $i < $length; $i++) {
                if ($content[$i] === '{') {
                    $depth++;
                } elseif ($content[$i] === '}') {
                    $depth--;
                    if ($depth === 0) {
                        $end = $i;
                        break;
                    }
                }
            }
            if ($depth !== 0) {
                continue;
            }
            $bodies[] = substr($content, $brace, $end - $brace + 1);
        }

        return $bodies;
    }

    /**
     * Removes or renames the WayneCasable and ReadOnlyAttributes imports so
     * they match how the final content references them. Returns the new head
     * and whether a WayneCasable import was removed.
     *
     * @return array{0: string, 1: bool}
     */
    private function cleanImports(string $head, string $candidate): array
    {
        $oldImport = 'use ' . self::OLD_NAMESPACE . '\\' . self::INTERFACE . ';';
        $newImport = 'use ' . self::NEW_NAMESPACE . '\\' . self::INTERFACE . ';';
        $oldRoImport = 'use ' . self::OLD_NAMESPACE . '\\' . self::READ_ONLY_TRAIT . ';';
        $newRoImport = 'use ' . self::NEW_NAMESPACE . '\\' . self::READ_ONLY_TRAIT . ';';
        $importRemoved = false;

        // The interface is now referenced by its fully qualified name, so its
        // import is dead unless a bare short-name reference survives elsewhere.
        $check = str_replace([$oldImport . "\n", $newImport . "\n"], '', $candidate);
        $bareUses = preg_match_all('/(?<![\w\\\\])' . self::INTERFACE . '\b/', $check);
        $hasOldImport = str_contains($head, $oldImport);
        $hasNewImport = str_contains($head, $newImport);
        if ($bareUses === 0) {
            if ($hasOldImport) {
                $head = self::removeLine($head, $oldImport);
                $importRemoved = true;
            }
            if ($hasNewImport) {
                $head = self::removeLine($head, $newImport);
                $importRemoved = true;
            }
        } elseif ($hasOldImport && !$hasNewImport) {
            $head = str_replace($oldImport, $newImport, $head);
        }

        // ReadOnlyAttributes keeps its import only when the short name is used.
        $roCheck = str_replace([$oldRoImport . "\n", $newRoImport . "\n"], '', $candidate);
        $roShortUsed = preg_match('/(?<![\w\\\\])' . self::READ_ONLY_TRAIT . '\b/', $roCheck) === 1;
        $hasOldRo = str_contains($head, $oldRoImport);
        $hasNewRo = str_contains($head, $newRoImport);
        if ($roShortUsed) {
            if ($hasOldRo && !$hasNewRo) {
                $head = str_replace($oldRoImport, $newRoImport, $head);
            } elseif (!$hasOldRo && !$hasNewRo) {
                $head = self::insertAfterLastImport($head, $newRoImport);
            }
        } else {
            if ($hasOldRo) {
                $head = self::removeLine($head, $oldRoImport);
            }
            if ($hasNewRo) {
                $head = self::removeLine($head, $newRoImport);
            }
        }

        return [$head, $importRemoved];
    }

    /**
     * Removes one line (by its exact text, newline included) from the text,
     * collapsing the blank line that would otherwise linger.
     */
    private static function removeLine(string $text, string $line): string
    {
        $needle = $line . "\n";
        $pos = strpos($text, $needle);
        if ($pos === false) {
            return $text;
        }
        if ($pos >= 2 && $text[$pos - 1] === "\n" && $text[$pos - 2] === "\n") {
            // A blank line precedes the target: drop it together with the line.
            return substr($text, 0, $pos - 1) . substr($text, $pos + strlen($needle));
        }

        return substr($text, 0, $pos) . substr($text, $pos + strlen($needle));
    }

    /**
     * Inserts an import line after the last existing import, or after the
     * namespace line when the file has none.
     */
    private static function insertAfterLastImport(string $head, string $import): string
    {
        $count = preg_match_all('/^[ \t]*use[ \t]+[^;]+;[ \t]*$/m', $head, $m, PREG_OFFSET_CAPTURE);
        if ($count > 0) {
            $last = $m[0][$count - 1];
            $at = $last[1] + strlen($last[0]);
            if ($at < strlen($head) && $head[$at] === "\n") {
                $at++;
            }

            return substr($head, 0, $at) . $import . "\n" . substr($head, $at);
        }
        if (preg_match('/^[ \t]*namespace[ \t]+[A-Za-z0-9_\\\\]+;[ \t]*\n/m', $head, $n)) {
            $at = strlen($n[0]);

            return substr($head, 0, $at) . "\n" . $import . "\n" . substr($head, $at);
        }

        return $head . "\n" . $import . "\n";
    }

    /**
     * The class whose body uses WayneCasable as a trait: the declaration
     * offset and the offset of its opening brace, or null.
     *
     * @return array{0: int, 1: int}|null
     */
    private function classRegion(string $content): ?array
    {
        $starts = [];
        if (preg_match_all('/^[ \t]*(?:final[ \t]+|abstract[ \t]+)?class[ \t]+[A-Za-z0-9_]+/m', $content, $m, PREG_OFFSET_CAPTURE) !== false) {
            foreach ($m[0] as $match) {
                $starts[] = $match[1];
            }
        }
        foreach ($starts as $i => $start) {
            $brace = strpos($content, '{', $start);
            if ($brace === false || $brace - $start > 500) {
                continue;
            }
            $next = $i + 1 < count($starts) ? $starts[$i + 1] : strlen($content);
            if (self::referencesTrait(substr($content, $brace, $next - $brace))) {
                return [$start, $brace];
            }
        }

        return null;
    }

    /**
     * Whether the text carries a trait-use line that mentions WayneCasable.
     */
    private static function referencesTrait(string $content): bool
    {
        return preg_match('/^[ \t]*use[ \t]+[^;]*' . self::INTERFACE . '[^;]*;/m', $content) === 1;
    }

    /**
     * Every `use Trait[, Trait];` statement in the text.
     *
     * @return list<array{0: int, 1: string, 2: list<string>}> offset, indent, trait names
     */
    private static function traitUseLines(string $content): array
    {
        $lines = [];
        if (preg_match_all('/^[ \t]*use[ \t]+([^;]+);[ \t]*$/m', $content, $m, PREG_OFFSET_CAPTURE) !== false) {
            foreach ($m[0] as $i => $match) {
                // The match starts at the line's first column, so the indent is
                // its own leading whitespace.
                $text = $m[0][$i][0];
                $indent = substr($text, 0, strlen($text) - strlen(ltrim($text, " \t")));
                $lines[] = [
                    $match[1],
                    $indent,
                    array_map('trim', explode(',', $m[1][$i][0])),
                ];
            }
        }

        return $lines;
    }

    /**
     * The run of whitespace at the end of the text.
     */
    private static function trailingWhitespace(string $text): string
    {
        $trimmed = rtrim($text);

        return substr($text, strlen($trimmed));
    }

    private function relative(string $base, string $file): string
    {
        $base = str_replace('\\', '/', rtrim($base, '/\\'));
        $file = str_replace('\\', '/', $file);

        return substr($file, strlen($base) + 1);
    }
