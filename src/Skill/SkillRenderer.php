<?php

declare(strict_types=1);

namespace Waynestate\Booster\Skill;

use Waynestate\Booster\Hop\Hop;
use Waynestate\Booster\Hop\HopRegistry;

/**
 * Renders the coding-tab playbooks (.agents/skills/<name>/SKILL.md) from the
 * hop registry, so the playbooks and the CLI cannot drift. The playbooks tell
 * an assistant to drive the same commands a person would type, and to stop for
 * a human to review and merge. `booster init --check` fails when one is stale.
 */
final class SkillRenderer
{
    /**
     * @return array<string, string> relative path (name/SKILL.md) to file content
     */
    public function render(HopRegistry $registry): array
    {
        $files = ['booster/SKILL.md' => $this->index($registry)];
        foreach ($registry->all() as $hop) {
            $files['booster-' . $hop->id . '/SKILL.md'] = $this->hop($hop);
        }

        return $files;
    }

    private function index(HopRegistry $registry): string
    {
        $list = '';
        foreach ($registry->all() as $hop) {
            $list .= sprintf("- `booster-%s`: %s\n", $hop->id, $hop->summary);
        }

        return <<<MD
        ---
        name: booster
        description: Plan and run a PHP or Laravel upgrade with BOOSTER. Use when an app must move to a newer supported PHP or Laravel version.
        ---

        # BOOSTER

        Generated by `booster init`. Do not edit by hand; run `booster init` again.

        1. Run `booster detect --path=<app>` and read the app type and versions.
        2. Run `booster plan --path=<app>` (or `--goal=php-74-to-84`) and show the plan to the person.
        3. For each step, follow the matching playbook below. Never skip a gate.
        4. Stop when the plan is done. A person reviews the diff and merges. Never push.

        Playbooks:

        {$list}
        MD . "\n";
    }

    private function hop(Hop $hop): string
    {
        $notes = '';
        foreach ($hop->notes as $note) {
            $notes .= '- ' . $note . "\n";
        }
        $links = '';
        foreach ($hop->links as $link) {
            $links .= '- ' . $link . "\n";
        }
        $review = $hop->extraReview ? "This is the riskiest PHP hop. Ask for extra tests before you apply it.\n\n" : '';
        $how = $hop->isManual()
            ? "BOOSTER has no automatic change for this hop. Follow the official guide below, then run the tests.\n"
            : "1. `booster run --path=<app> --dry-run` and read every diff.\n2. `booster run --path=<app>` applies the plan and stops at the first failing gate.\n3. If a hop is capped, split the work with `--skip`; do not raise `--max-changes` blindly.\n";

        return <<<MD
        ---
        name: booster-{$hop->id}
        description: {$hop->summary}
        ---

        # {$hop->id}

        Generated by `booster init`. Do not edit by hand.

        {$hop->summary}

        {$review}{$how}
        What Rector cannot do (check these by hand):

        {$notes}
        Official notes:

        {$links}
        MD . "\n";
    }
}
