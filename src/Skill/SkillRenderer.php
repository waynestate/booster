<?php

declare(strict_types=1);

namespace Waynestate\Booster\Skill;

use Waynestate\Booster\Hop\Hop;
use Waynestate\Booster\Hop\HopKind;
use Waynestate\Booster\Hop\HopRegistry;

/**
 * Renders the coding-tab playbooks (.agents/skills/<name>/SKILL.md) from the
 * hop registry, so the playbooks and the CLI cannot drift. The playbooks tell
 * an assistant to drive the same commands a person would type, and to stop for
 * a human to review and merge. `booster init --check` fails when one is stale.
 */
final class SkillRenderer
{
    /**
     * Tries an assistant gets at one failure before it hands the hop back to a
     * person. Booster is deterministic, so a fourth identical run is not
     * persistence, it is a screensaver.
     */
    public const MAX_TRIES = 3;

    /**
     * @return array<string, string> relative path (name/SKILL.md) to file content
     */
    public function render(HopRegistry $registry): array
    {
        $files = ['booster/SKILL.md' => $this->index($registry)];
        foreach ($registry->all() as $hop) {
            $files['booster-' . $hop->id . '/SKILL.md'] = $this->hop($hop);
        }

        return $files;
    }

    private function index(HopRegistry $registry): string
    {
        $list = '';
        foreach ($registry->all() as $hop) {
            $list .= sprintf("- `booster-%s`: %s\n", $hop->id, $hop->summary);
        }
        $tries = self::MAX_TRIES;

        return <<<MD
        ---
        name: booster
        description: Plan and run a PHP or Laravel upgrade with Booster. Use when an app must move to a newer supported PHP or Laravel version.
        ---

        # Booster

        Generated by `booster init`. Do not edit by hand; run `booster init` again.

        1. Run `booster detect --path=<app>` and read the app type and versions.
        2. Run `booster plan --path=<app>` (or `--goal=php-74-to-84`) and show the plan to the person.
        3. For each step, follow the matching playbook below. Never skip a gate.
        4. When a gate fails, follow the playbook's "When a gate fails" steps: work from the real output, and after {$tries} tries at one failure, stop and hand it to the person.
        5. Stop when the plan is done. A person reviews the diff and merges. Never push.

        Optional: ADVISOR gives the agent read-only answers about the WSU stack (supported versions, CREED rules, which project owns what). Add it to the app when the person wants it:

        - `composer require --dev waynestate/advisor`
        - `php vendor/bin/advisor install --client=claude --write`

        Booster works without ADVISOR.

        Playbooks:

        {$list}
        MD . "\n";
    }

    private function hop(Hop $hop): string
    {
        $notes = '';
        foreach ($hop->notes as $note) {
            $notes .= '- ' . $note . "\n";
        }
        $links = '';
        foreach ($hop->links as $link) {
            $links .= '- ' . $link . "\n";
        }
        $review = $hop->extraReview ? "This is the riskiest PHP hop. Ask for extra tests, or a replay file (`booster replay init`, then `booster run --replay`), before you apply it.\n\n" : '';
        $how = $hop->isManual()
            ? "Booster has no automatic change for this hop. Follow the official guide below, then run the tests.\n"
            : "1. `booster run --path=<app> --dry-run` and read every diff.\n2. `booster run --path=<app>` applies the plan and stops at the first failing gate.\n3. If a hop is over the review threshold (200 files), read its per-rule summary, then apply it with `--max-changes=N`. Use `--skip` to leave a rule out.\n";
        $failure = $this->failureSection($hop);
        $boost = $this->boostSection($hop);

        return <<<MD
        ---
        name: booster-{$hop->id}
        description: {$hop->summary}
        ---

        # {$hop->id}

        Generated by `booster init`. Do not edit by hand.

        {$hop->summary}

        {$review}{$how}
        {$failure}
        {$boost}What Rector cannot do (check these by hand):

        {$notes}
        Official notes:

        {$links}
        MD . "\n";
    }

    /**
     * What an assistant does when the hop's gate goes red: feed the fix the real
     * output and the files it names (not a summary), fix one cause per try, and
     * hand the hop back to a person after MAX_TRIES tries at one failure. The
     * recipe it follows is the one people get in docs/recipes.md ("After a stop").
     * A manual hop has no Booster gate, so its gate is the tests the assistant
     * runs after its own change.
     */
    private function failureSection(Hop $hop): string
    {
        $tries = self::MAX_TRIES;
        $stop = sprintf('Stop after %d tries at the same failure, or sooner when a try changes nothing. Show the person the last output and what you tried.', $tries);

        $lines = $hop->isManual()
            ? [
                'When a gate fails (for this hop, the tests you run after your change):',
                '',
                '1. Work from the exact failing output, the files it names, their tests and the notes below, not from a summary of them.',
                '2. Fix one cause, then run the tests again.',
                '3. ' . $stop,
            ]
            : [
                "When a gate fails, the run stops and leaves this hop's changes in place:",
                '',
                '1. Read the report for this hop: the phase that failed and the last lines of output. Work from that exact output, the files it names, their tests and the notes below, not from a summary of them.',
                '2. Fix one cause: code the hop could not change, a package that blocks the hop (`booster plan` names it), or a test that depends on old behavior.',
                '3. Commit the fix on its own, then run `booster run --path=<app>` again. Booster plans from the versions the app is on now, so finished hops are not repeated.',
                '4. ' . $stop,
            ];
        $lines[] = '';
        $lines[] = 'Never delete, skip or loosen a test to turn a gate green, and never add `--skip-gate`, `--allow-failing-baseline` or `--skip` unless the person asks for it.';

        return implode("\n", $lines) . "\n";
    }

    /**
     * The Laravel Boost section of a hop playbook: prompts for apps that carry
     * laravel/boost. Boost reads the app; it never changes it, and it never
     * overrides a gate.
     */
    private function boostSection(Hop $hop): string
    {
        $prompts = match ($hop->kind) {
            HopKind::Php => [
                sprintf('Use `search-docs` for removed or deprecated functions in PHP %s and check each one against the files Booster changed.', $hop->to),
                'Use `tinker` to load a changed class and confirm it still loads.',
                'Use `application-info` to confirm the reported versions after the hop.',
                'Run `last-error` and `read-log-entries` after the tests.',
            ],
            HopKind::Laravel => [
                sprintf("Use `search-docs` for the Laravel %s upgrade guide and list every breaking change that touches this app's `list-routes` and `get-config` output.", $hop->to),
                sprintf("Use `database-schema` to look at the tables, and check the database server's version against the minimum Laravel %s needs, before you apply the hop.", $hop->to),
                'Use `list-artisan-commands` and `list-routes` before the hop, then compare the output after it.',
                'Run `last-error` and `read-log-entries` after the tests.',
            ],
            HopKind::Phpunit => [
                sprintf("Use `search-docs` for the PHPUnit %s migration notes and list the changes that touch this app's tests.", $hop->to),
                "Use `get-config` to read the app's test-related config before you change phpunit.xml.",
                'Run `last-error` and `read-log-entries` after the tests.',
            ],
            HopKind::Sesame => [
                'Use `get-config` to copy the current wayne-cas settings before the swap.',
                'Use `list-routes` to note the sign-in and sign-out routes you will re-test.',
                'Run `last-error` and `read-log-entries` after a test login.',
            ],
            HopKind::WayneUi => [
                "Use `search-docs` for WayneUI's MIGRATING guide and check it against every file Booster changed.",
                'Use `list-routes` to note the pages you will check in both light and dark themes.',
                'Run `last-error` and `read-log-entries` after the tests.',
            ],
            HopKind::Vue => [
                sprintf("Use `search-docs` for the Vue %s migration guide and list the breaking changes that touch this app's components.", $hop->to),
                'Use `browser-logs` after a page load to catch the Vue warnings the console prints.',
                'Run `last-error` and `read-log-entries` after the tests.',
            ],
            HopKind::Framework => [
                'Use `search-docs` for the Doctrine ORM 2.20, Smarty 4 or Slim 4 docs, whichever the hop moved, and check them against every file Booster changed.',
                'Use `list-routes` (or the app\'s own route list) to pick the pages the replay file should hit.',
                'Run `last-error` and `read-log-entries` after the replay.',
            ],
            HopKind::Node => [
                "Use `search-docs` for the Vite front-end docs and check the app's build config against them.",
                'Use `browser-logs` after a page load to catch front-end errors the change might surface.',
                'Run `last-error` and `read-log-entries` after the build and the tests.',
            ],
        };

        $lines = ["Only if the app has Laravel Boost (`booster detect` says so):", ''];
        foreach ($prompts as $prompt) {
            $lines[] = '- ' . $prompt;
        }
        $lines[] = '';
        $lines[] = "Boost is read-only help. Booster's gate stays the authority: never skip a gate because Boost says so.";

        return implode("\n", $lines) . "\n\n";
    }
}
