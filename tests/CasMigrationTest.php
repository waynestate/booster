        self::assertSame(1, substr_count($model, 'use \Waynestate\Sesame\WayneCas\ReadOnlyAttributes;'));
        self::assertStringNotContainsString('WSU\\WayneCas', $model);
        self::assertStringNotContainsString('use WayneCasable;', $model);
    }

