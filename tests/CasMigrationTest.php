<?php

declare(strict_types=1);

namespace Waynestate\Booster\Tests;

use FilesystemIterator;
use ParseError;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Waynestate\Booster\Run\CasMigration;
use Waynestate\Booster\Run\CasMigrationResult;

final class CasMigrationTest extends TestCase
{
    private function migrate(string $dir, bool $dryRun = false): CasMigrationResult
    {
        return (new CasMigration())->migrate($dir, $dryRun);
    }

    public function test_it_writes_the_sesame_config_from_the_old_root(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $result = $this->migrate($dir);

        $config = (string) file_get_contents($dir . '/config/sesame.php');
        self::assertStringContainsString("'base_url' => Setting::get('SESAME_CAS_BASE_URL') ?? 'https://cas.example.edu/cas'", $config);
        self::assertStringContainsString("'user_resolver' => env('SESAME_USER_RESOLVER', \Waynestate\Sesame\WayneCas\UserResolver::class)", $config);
        self::assertStringContainsString('Generated by Booster from config/wayne-cas.php', $config);
        try {
            self::assertIsArray(token_get_all($config, TOKEN_PARSE));
        } catch (ParseError $e) {
            self::fail('the generated config/sesame.php does not parse: ' . $e->getMessage());
        }
        // The loaded config resolves the old root and the compat resolver, and
        // an environment value still wins over the fallback.
        $loaded = $this->loadSesameConfig($dir . '/config/sesame.php');
        self::assertSame('cas', $loaded['driver']);
        self::assertSame('https://cas.example.edu/cas', $loaded['cas']['base_url']);
        self::assertSame('2.0', $loaded['cas']['protocol']);
        self::assertSame('Waynestate\Sesame\WayneCas\UserResolver', $loaded['user_resolver']);
        self::assertArrayHasKey('fake', $loaded);
        putenv('SESAME_CAS_BASE_URL=https://academica.example.edu/cas');
        try {
            $loaded = $this->loadSesameConfig($dir . '/config/sesame.php');
            self::assertSame('https://academica.example.edu/cas', $loaded['cas']['base_url']);
        } finally {
            putenv('SESAME_CAS_BASE_URL');
        }
        // The old config stays exactly as it was.
        self::assertSame(
            (string) file_get_contents($this->example('laravel-wayne-cas') . '/config/wayne-cas.php'),
            (string) file_get_contents($dir . '/config/wayne-cas.php'),
        );
        self::assertSame(['config/sesame.php', 'app/User.php'], array_map(static fn(array $f): string => $f['file'], $result->files));
    }

    public function test_the_app_vendor_config_wins_over_the_bundled_copy(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        mkdir($dir . '/vendor/waynestate/sesame/config', 0775, true);
        $bundled = (string) file_get_contents(dirname(__DIR__) . '/resources/sesame/config/sesame.php');
        file_put_contents($dir . '/vendor/waynestate/sesame/config/sesame.php', str_replace('declare(strict_types=1);', "declare(strict_types=1);\n// vendor-copy-marker", $bundled));
        $result = $this->migrate($dir);

        self::assertStringContainsString('vendor-copy-marker', (string) file_get_contents($dir . '/config/sesame.php'));
        self::assertStringContainsString('the app\'s vendor/waynestate/sesame config', implode(' ', $result->changes));
    }

    public function test_a_published_config_without_the_expected_lines_writes_nothing(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        mkdir($dir . '/vendor/waynestate/sesame/config', 0775, true);
        $bundled = (string) file_get_contents(dirname(__DIR__) . '/resources/sesame/config/sesame.php');
        file_put_contents($dir . '/vendor/waynestate/sesame/config/sesame.php', str_replace("'base_url' => Setting::get('SESAME_CAS_BASE_URL'),", "'base_url' => env('SESAME_CAS_BASE_URL'),", $bundled));
        $result = $this->migrate($dir);

        self::assertFileDoesNotExist($dir . '/config/sesame.php');
        self::assertStringContainsString('could not find the exact base_url and user_resolver lines', implode(' ', $result->manual));
    }

    public function test_it_leaves_an_existing_sesame_config_alone(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        file_put_contents($dir . '/config/sesame.php', "<?php\n\nreturn [];\n");
        $result = $this->migrate($dir);

        self::assertSame("<?php\n\nreturn [];\n", (string) file_get_contents($dir . '/config/sesame.php'));
        $manual = implode(' ', $result->manual);
        self::assertStringContainsString('config/sesame.php already exists', $manual);
        self::assertStringContainsString('https://cas.example.edu/cas', $manual);
        self::assertNotContains('config/sesame.php', array_map(static fn(array $f): string => $f['file'], $result->files));
    }

    public function test_it_rewrites_the_user_model_to_implement_the_interface(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $this->migrate($dir);

        $expected = <<<'PHP'
