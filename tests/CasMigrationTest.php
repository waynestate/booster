    public function test_it_writes_the_sesame_config_from_the_old_root(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $result = $this->migrate($dir);

        $config = (string) file_get_contents($dir . '/config/sesame.php');
        self::assertStringContainsString("'base_url' => Setting::get('SESAME_CAS_BASE_URL') ?? 'https://cas.example.edu/cas'", $config);
        self::assertStringContainsString("'user_resolver' => env('SESAME_USER_RESOLVER', \Waynestate\Sesame\WayneCas\UserResolver::class)", $config);
        self::assertStringContainsString('Generated by Booster from config/wayne-cas.php', $config);
        try {
            self::assertIsArray(token_get_all($config, TOKEN_PARSE));
        } catch (ParseError $e) {
            self::fail('the generated config/sesame.php does not parse: ' . $e->getMessage());
        }
        // The loaded config resolves the old root and the compat resolver, and
        // an environment value still wins over the fallback.
        $loaded = $this->loadSesameConfig($dir . '/config/sesame.php');
        self::assertSame('cas', $loaded['driver']);
        self::assertSame('https://cas.example.edu/cas', $loaded['cas']['base_url']);
        self::assertSame('2.0', $loaded['cas']['protocol']);
        self::assertSame('Waynestate\Sesame\WayneCas\UserResolver', $loaded['user_resolver']);
        self::assertArrayHasKey('fake', $loaded);
        putenv('SESAME_CAS_BASE_URL=https://academica.example.edu/cas');
        try {
            $loaded = $this->loadSesameConfig($dir . '/config/sesame.php');
            self::assertSame('https://academica.example.edu/cas', $loaded['cas']['base_url']);
        } finally {
            putenv('SESAME_CAS_BASE_URL');
        }
        // The old config stays exactly as it was.
        self::assertSame(
            (string) file_get_contents($this->example('laravel-wayne-cas') . '/config/wayne-cas.php'),
            (string) file_get_contents($dir . '/config/wayne-cas.php'),
        );
        self::assertSame(
            ['config/sesame.php', 'app/Http/Kernel.php', 'app/Providers/RouteServiceProvider.php', 'config/auth.php', 'app/User.php'],
            array_map(static fn(array $f): string => $f['file'], $result->files),
        );
    }

