    /** Loads a generated config/sesame.php with the test doubles in place. */
    private function loadSesameConfig(string $file): array
    {
        require_once __DIR__ . '/support/sesame-config-stubs.php';

        return include $file;
    }

    /**
     * Every file in the tree, by relative path and content.
     *
     * @return array<string, string>
     */
    private function snapshot(string $dir): array
    {
        $out = [];
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->isFile()) {
                $relative = str_replace('\\', '/', substr($file->getPathname(), strlen($dir) + 1));
                $out[$relative] = (string) file_get_contents($file->getPathname());
            }
        }
        ksort($out);

        return $out;
    }
