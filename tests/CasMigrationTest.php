<?php

declare(strict_types=1);

namespace Waynestate\Booster\Tests;

use FilesystemIterator;
use ParseError;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Waynestate\Booster\Run\CasMigration;
use Waynestate\Booster\Run\CasMigrationResult;

final class CasMigrationTest extends TestCase
{
    private function migrate(string $dir, bool $dryRun = false): CasMigrationResult
    {
        return (new CasMigration())->migrate($dir, $dryRun);
    }

    public function test_it_writes_the_sesame_config_from_the_old_root(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $result = $this->migrate($dir);

        $config = (string) file_get_contents($dir . '/config/sesame.php');
        self::assertStringContainsString("'driver' => 'cas'", $config);
        self::assertStringContainsString("'base_url' => 'https://cas.example.edu/cas'", $config);
        self::assertStringContainsString('Generated by Booster from config/wayne-cas.php', $config);
        try {
            self::assertIsArray(token_get_all($config, TOKEN_PARSE));
        } catch (ParseError $e) {
            self::fail('the generated config/sesame.php does not parse: ' . $e->getMessage());
        }
        // The old config stays exactly as it was.
        self::assertSame(
            (string) file_get_contents($this->example('laravel-wayne-cas') . '/config/wayne-cas.php'),
            (string) file_get_contents($dir . '/config/wayne-cas.php'),
        );
        self::assertSame(['config/sesame.php', 'app/User.php'], array_map(static fn(array $f): string => $f['file'], $result->files));
    }

    public function test_it_leaves_an_existing_sesame_config_alone(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        file_put_contents($dir . '/config/sesame.php', "<?php\n\nreturn [];\n");
        $result = $this->migrate($dir);

        self::assertSame("<?php\n\nreturn [];\n", (string) file_get_contents($dir . '/config/sesame.php'));
        $manual = implode(' ', $result->manual);
        self::assertStringContainsString('config/sesame.php already exists', $manual);
        self::assertStringContainsString('https://cas.example.edu/cas', $manual);
        self::assertNotContains('config/sesame.php', array_map(static fn(array $f): string => $f['file'], $result->files));
    }

    public function test_it_rewrites_the_user_model_to_implement_the_interface(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $this->migrate($dir);

        $expected = <<<'PHP'
        <?php

        namespace App;

        use Waynestate\Sesame\WayneCas\ReadOnlyAttributes;
        use Waynestate\Sesame\WayneCas\WayneCasable;

        class User implements WayneCasable
        {
            use ReadOnlyAttributes;
        }
        PHP . "\n";
        self::assertSame($expected, (string) file_get_contents($dir . '/app/User.php'));
    }

    public function test_duo_is_listed_as_manual_when_use2fa_is_on(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $result = $this->migrate($dir);

        $manual = implode(' ', $result->manual);
        foreach (['use2FA', 'DUO_HOSTNAME', 'DUO_IKEY', 'DUO_SKEY', 'DUO_AKEY'] as $needle) {
            self::assertStringContainsString($needle, $manual);
        }
        self::assertStringContainsString('config/wayne-cas.php: left in place', $manual);
    }

    public function test_dry_run_changes_nothing_but_reports_the_work(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        $before = $this->snapshot($dir);
        $result = $this->migrate($dir, true);

        self::assertSame($before, $this->snapshot($dir));
        self::assertFileDoesNotExist($dir . '/config/sesame.php');
        self::assertCount(2, $result->changes);
        self::assertStringStartsWith('Dry run: would write config/sesame.php', $result->changes[0]);
        self::assertStringStartsWith('Dry run: would rewrite app/User.php', $result->changes[1]);
    }

    public function test_a_missing_old_config_is_a_manual_note(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        unlink($dir . '/config/wayne-cas.php');
        $result = $this->migrate($dir);

        self::assertFileDoesNotExist($dir . '/config/sesame.php');
        self::assertStringContainsString('config/wayne-cas.php is missing', implode(' ', $result->manual));
    }

    public function test_an_unreadable_root_is_a_manual_note(): void
    {
        $dir = $this->copyExample('laravel-wayne-cas');
        file_put_contents($dir . '/config/wayne-cas.php', "<?php\n\nreturn [\n    'root' => env('CAS_ROOT'),\n];\n");
        $result = $this->migrate($dir);

        self::assertFileDoesNotExist($dir . '/config/sesame.php');
        self::assertStringContainsString('could not read a plain string', implode(' ', $result->manual));
    }

    public function test_it_keeps_existing_implements_and_adds_the_interface(): void
    {
        $dir = $this->tempDir();
        mkdir($dir . '/app', 0775, true);
        file_put_contents($dir . '/app/Member.php', <<<'PHP'
        <?php

        namespace App;

        use Illuminate\Contracts\Auth\MustVerifyEmail;
        use WSU\WayneCas\WayneCasable;

        class Member implements MustVerifyEmail
        {
            use WayneCasable;
        }
        PHP . "\n");
        $this->migrate($dir);

        $model = (string) file_get_contents($dir . '/app/Member.php');
        self::assertStringContainsString('class Member implements MustVerifyEmail, WayneCasable', $model);
        self::assertStringContainsString("use Waynestate\\Sesame\\WayneCas\\WayneCasable;\nuse Waynestate\\Sesame\\WayneCas\\ReadOnlyAttributes;", $model);
        self::assertStringContainsString('    use ReadOnlyAttributes;', $model);
        self::assertSame(1, substr_count($model, 'use ReadOnlyAttributes;'));
    }

    public function test_it_does_not_duplicate_read_only_attributes(): void
    {
        $dir = $this->tempDir();
        mkdir($dir . '/app', 0775, true);
        file_put_contents($dir . '/app/User.php', <<<'PHP'
        <?php

        namespace App;

        use WSU\WayneCas\ReadOnlyAttributes;
        use WSU\WayneCas\WayneCasable;

        class User
        {
            use WayneCasable;

            use ReadOnlyAttributes;
        }
        PHP . "\n");
        $this->migrate($dir);

        $model = (string) file_get_contents($dir . '/app/User.php');
        self::assertStringContainsString('class User implements WayneCasable', $model);
        self::assertSame(1, substr_count($model, 'use ReadOnlyAttributes;'));
        self::assertStringNotContainsString('use WayneCasable;', $model);
    }

    public function test_a_model_without_a_recognisable_import_is_left_alone(): void
    {
        $dir = $this->tempDir();
        mkdir($dir . '/app', 0775, true);
        $source = "<?php\n\nclass Ghost\n{\n    use WayneCasable;\n}\n";
        file_put_contents($dir . '/app/Ghost.php', $source);
        $result = $this->migrate($dir);

        self::assertSame($source, (string) file_get_contents($dir . '/app/Ghost.php'));
        self::assertStringContainsString('app/Ghost.php: BOOSTER found no import for WayneCasable', implode(' ', $result->manual));
    }

    /**
     * Every file in the tree, by relative path and content.
     *
     * @return array<string, string>
     */
    private function snapshot(string $dir): array
    {
        $out = [];
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->isFile()) {
                $relative = str_replace('\\', '/', substr($file->getPathname(), strlen($dir) + 1));
                $out[$relative] = (string) file_get_contents($file->getPathname());
            }
        }
        ksort($out);

        return $out;
    }
}
