<?php

declare(strict_types=1);

namespace Waynestate\Booster\Tests;

use Psr\Container\NotFoundExceptionInterface;
use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use Psr\Http\Server\RequestHandlerInterface;
use Slim\Factory\AppFactory;
use Slim\Psr7\Factory\ServerRequestFactory;
use Slim\Psr7\Factory\StreamFactory;
use Slim\Psr7\Response;
use Waynestate\Booster\Run\Slim\LegacyStubs;

/**
 * The files the Slim 3 to 4 hop copies into an app, run for real: the
 * generated classes are loaded under a namespace of their own and driven
 * through slim/slim 4.15 and slim/psr7 (dev dependencies). Pimple is not a
 * Booster dependency, so a small stand-in with Pimple's lazy, shared services
 * is defined here.
 */
final class SlimLegacyStubsTest extends TestCase
{
    private static string $namespace = '';

    private string $errorLog = '';

    private string $previousErrorLog = '';

    public static function setUpBeforeClass(): void
    {
        self::definePimpleStandIn();

        self::$namespace = 'BoosterSlimStubs' . bin2hex(random_bytes(4)) . '\\Legacy';
        $dir = sys_get_temp_dir() . '/booster-slim-stubs-' . bin2hex(random_bytes(4));
        mkdir($dir);
        foreach (['container', 'doublePass', 'app'] as $stub) {
            $file = $dir . '/' . $stub . '.php';
            file_put_contents($file, LegacyStubs::$stub(self::$namespace));
            require $file;
            unlink($file);
        }
        rmdir($dir);
    }

    protected function setUp(): void
    {
        parent::setUp();
        // Slim's error middleware logs each handled error through error_log().
        $this->errorLog = (string) tempnam(sys_get_temp_dir(), 'booster-slim-log');
        $this->previousErrorLog = (string) ini_get('error_log');
        ini_set('error_log', $this->errorLog);
    }

    protected function tearDown(): void
    {
        ini_set('error_log', $this->previousErrorLog);
        @unlink($this->errorLog);
        self::forgetAppFactoryContainer();
        parent::tearDown();
    }

    /** AppFactory keeps the container statically; later apps (and Slim tests) must not inherit it. */
    private static function forgetAppFactoryContainer(): void
    {
        (new \ReflectionProperty(AppFactory::class, 'container'))->setValue(null, null);
    }

    public function test_every_stub_is_valid_php(): void
    {
        foreach (['container', 'doublePass', 'app'] as $stub) {
            $code = LegacyStubs::$stub('App\\Slim4');

            self::assertStringStartsWith("<?php\n", $code, $stub);
            self::assertStringContainsString('Generated by Booster for the Slim 3 to 4 move; delete when no longer needed', $code, $stub);
            self::assertStringContainsString("declare(strict_types=1);\n", $code, $stub);
            self::assertStringContainsString("namespace App\\Slim4;\n", $code, $stub);
            \PhpToken::tokenize($code, TOKEN_PARSE);
        }

        self::assertStringContainsString('final class LegacyContainer extends \\Pimple\\Container implements \\Psr\\Container\\ContainerInterface', LegacyStubs::container('App'));
        self::assertStringContainsString('final class LegacyNotFound extends \\RuntimeException implements \\Psr\\Container\\NotFoundExceptionInterface', LegacyStubs::container('App'));
        self::assertStringContainsString('final class LegacyDoublePass implements \\Psr\\Http\\Server\\MiddlewareInterface', LegacyStubs::doublePass('App'));
        self::assertStringContainsString('final class LegacyApp', LegacyStubs::app('App'));
        self::assertStringContainsString("namespace App\\Slim4;\n", LegacyStubs::app('\\App\\Slim4\\'));
    }

    public function test_container_serves_array_property_and_get_styles(): void
    {
        $container = self::make('LegacyContainer', ['settings' => ['displayErrorDetails' => true]]);
        $container['service'] = static fn(\ArrayAccess $c): \ArrayObject => new \ArrayObject(['details' => $c['settings']['displayErrorDetails']]);

        self::assertInstanceOf(\Psr\Container\ContainerInterface::class, $container);
        self::assertTrue($container['settings']['displayErrorDetails']);
        self::assertTrue($container->settings['displayErrorDetails']);
        self::assertTrue($container->get('settings')['displayErrorDetails']);

        $service = $container->get('service');
        self::assertSame(['details' => true], $service->getArrayCopy());
        self::assertSame($service, $container['service']);
        self::assertSame($service, $container->service);
        self::assertTrue($container->has('service'));
        self::assertTrue(isset($container->service));
        self::assertFalse($container->has('missing'));
        self::assertFalse(isset($container->missing));
    }

    public function test_container_get_unknown_id_throws_not_found(): void
    {
        $container = self::make('LegacyContainer');

        try {
            $container->get('missing');
            self::fail('get() of an unknown id must throw');
        } catch (NotFoundExceptionInterface $e) {
            self::assertSame(self::$namespace . '\\LegacyNotFound', $e::class);
            self::assertInstanceOf(\RuntimeException::class, $e);
            self::assertStringContainsString('missing', $e->getMessage());
        }
    }

    public function test_double_pass_calls_legacy_with_a_next_that_reaches_the_handler(): void
    {
        $handler = new class implements RequestHandlerInterface {
            public ?ServerRequestInterface $seen = null;

            public function handle(ServerRequestInterface $request): ResponseInterface
            {
                $this->seen = $request;

                return (new Response(201))->withHeader('X-Inner', 'kept');
            }
        };
        $legacy = static function (ServerRequestInterface $request, ResponseInterface $response, callable $next): ResponseInterface {
            $response = $response->withHeader('X-Session-Expires', '1800')->withHeader('X-Inner', 'outer');
            $answer = $next($request->withAttribute('legacy', 'ran'), $response);

            return $answer->withHeader('X-After', 'yes');
        };

        $middleware = self::make('LegacyDoublePass', $legacy);
        self::assertInstanceOf(\Psr\Http\Server\MiddlewareInterface::class, $middleware);
        $response = $middleware->process(self::request('GET', '/'), $handler);

        self::assertNotNull($handler->seen);
        self::assertSame('ran', $handler->seen->getAttribute('legacy'));
        self::assertSame(201, $response->getStatusCode());
        self::assertSame('1800', $response->getHeaderLine('X-Session-Expires'));
        self::assertSame('kept', $response->getHeaderLine('X-Inner'));
        self::assertSame('yes', $response->getHeaderLine('X-After'));

        // A middleware already on PSR-15 (a companion on its Slim 4 line) runs as it is.
        $psr15 = new class implements \Psr\Http\Server\MiddlewareInterface {
            public function process(ServerRequestInterface $request, RequestHandlerInterface $handler): ResponseInterface
            {
                return $handler->handle($request->withAttribute('legacy', 'psr15'))->withHeader('X-Psr15', 'yes');
            }
        };
        $passed = self::make('LegacyDoublePass', $psr15)->process(self::request('GET', '/'), $handler);
        self::assertSame('psr15', $handler->seen->getAttribute('legacy'));
        self::assertSame('yes', $passed->getHeaderLine('X-Psr15'));
        self::assertSame(201, $passed->getStatusCode());
    }

    public function test_double_pass_returns_an_early_response_without_calling_next(): void
    {
        $handler = new class implements RequestHandlerInterface {
            public bool $called = false;

            public function handle(ServerRequestInterface $request): ResponseInterface
            {
                $this->called = true;

                return new Response(200);
            }
        };
        $invokable = new class {
            public function __invoke(ServerRequestInterface $request, ResponseInterface $response, callable $next): ResponseInterface
            {
                $response->getBody()->write('sign in first');

                return $response->withStatus(401);
            }
        };

        $response = self::make('LegacyDoublePass', $invokable)->process(self::request('GET', '/'), $handler);

        self::assertFalse($handler->called);
        self::assertSame(401, $response->getStatusCode());
        self::assertSame('sign in first', (string) $response->getBody());
    }

    public function test_finish_orders_error_middleware_outermost(): void
    {
        $app = self::call('LegacyApp', 'create', ['settings' => ['displayErrorDetails' => false]]);
        $app->get('/boom', function ($request, $response) {
            throw new \RuntimeException('route failed');
        });
        self::call('LegacyApp', 'finish', $app);

        // Routing runs inside the error middleware, so a miss is a 404 answer, not an exception.
        self::assertSame(404, $app->handle(self::request('GET', '/nowhere'))->getStatusCode());
        self::assertSame(405, $app->handle(self::request('POST', '/boom'))->getStatusCode());

        $failed = $app->handle(self::request('GET', '/boom'));
        self::assertSame(500, $failed->getStatusCode());
        self::assertStringNotContainsString('route failed', (string) $failed->getBody());
    }

    public function test_app_create_and_finish_serve_a_route(): void
    {
        $app = self::call('LegacyApp', 'create', ['settings' => ['displayErrorDetails' => true, 'site' => 'Booster']]);
        self::assertInstanceOf(\Slim\App::class, $app);

        $container = $app->getContainer();
        self::assertInstanceOf(self::$namespace . '\\LegacyContainer', $container);
        self::assertSame('Booster', $container['settings']['site']);
        self::assertSame('append', $container['settings']['outputBuffering'], 'Slim 3 defaults fill the settings');

        $app->get('/hello/{name}', function ($request, $response, array $args) {
            // Slim binds route closures to the container, as Slim 3 did.
            $response->getBody()->write('Hello ' . $args['name'] . ' from ' . $this->get('settings')['site']);

            return $response;
        });
        $app->get('/echo', function ($request, $response) {
            echo 'echoed ';
            $response->getBody()->write('written');

            return $response;
        });
        self::call('LegacyApp', 'finish', $app);

        $response = $app->handle(self::request('GET', '/hello/world'));
        self::assertSame(200, $response->getStatusCode());
        self::assertSame('Hello world from Booster', (string) $response->getBody());

        // Slim 3's default outputBuffering ('append') and addContentLengthHeader (true) hold.
        $echoed = $app->handle(self::request('GET', '/echo'));
        self::assertSame('writtenechoed ', (string) $echoed->getBody());
        self::assertSame((string) strlen('writtenechoed '), $echoed->getHeaderLine('Content-Length'));
    }

    public function test_finish_adds_body_parsing_and_cache_file_only_when_set(): void
    {
        $plain = self::call('LegacyApp', 'create');
        $plain->post('/json', function ($request, $response) {
            $response->getBody()->write((string) json_encode($request->getParsedBody()));

            return $response;
        });
        self::call('LegacyApp', 'finish', $plain);

        $request = self::request('POST', '/json')
            ->withHeader('Content-Type', 'application/json')
            ->withBody((new StreamFactory())->createStream('{"a":1}'));
        self::assertSame('{"a":1}', (string) $plain->handle($request)->getBody());
        self::assertNull($plain->getRouteCollector()->getCacheFile());

        $cacheFile = sys_get_temp_dir() . '/booster-slim-routes-' . bin2hex(random_bytes(4)) . '.php';
        $cached = self::call('LegacyApp', 'create', ['settings' => ['routerCacheFile' => $cacheFile, 'outputBuffering' => false, 'addContentLengthHeader' => false]]);
        self::call('LegacyApp', 'finish', $cached);
        self::assertSame($cacheFile, $cached->getRouteCollector()->getCacheFile());

        $empty = self::call('LegacyApp', 'create', ['settings' => ['routerCacheFile' => '']]);
        self::call('LegacyApp', 'finish', $empty);
        self::assertNull($empty->getRouteCollector()->getCacheFile());

        // An app built without create() (no settings at all) still finishes.
        self::forgetAppFactoryContainer();
        $bare = AppFactory::create();
        self::assertSame($bare, self::call('LegacyApp', 'finish', $bare));
    }

    private static function request(string $method, string $path): ServerRequestInterface
    {
        return (new ServerRequestFactory())->createServerRequest($method, 'http://localhost' . $path);
    }

    private static function make(string $class, mixed ...$args): object
    {
        $fqcn = self::$namespace . '\\' . $class;

        return new $fqcn(...$args);
    }

    private static function call(string $class, string $method, mixed ...$args): mixed
    {
        $fqcn = self::$namespace . '\\' . $class;

        return $fqcn::$method(...$args);
    }

    /**
     * Pimple 3's behaviour, in brief: ArrayAccess over values given to the
     * constructor or set later; a closure or invokable is a service, called
     * with the container on first read and shared after that.
     */
    private static function definePimpleStandIn(): void
    {
        if (!class_exists(\Pimple\Container::class, false)) {
            eval(<<<'PHP'
                namespace Pimple;

                class Container implements \ArrayAccess
                {
                    private array $values = [];

                    private array $resolved = [];

                    public function __construct(array $values = [])
                    {
                        foreach ($values as $id => $value) {
                            $this->offsetSet($id, $value);
                        }
                    }

                    public function offsetExists(mixed $id): bool
                    {
                        return array_key_exists($id, $this->values);
                    }

                    public function offsetGet(mixed $id): mixed
                    {
                        if (!array_key_exists($id, $this->values)) {
                            throw new \InvalidArgumentException(sprintf('Identifier "%s" is not defined.', $id));
                        }
                        if (array_key_exists($id, $this->resolved)) {
                            return $this->resolved[$id];
                        }
                        $value = $this->values[$id];
                        if (is_object($value) && method_exists($value, '__invoke')) {
                            return $this->resolved[$id] = $value($this);
                        }

                        return $value;
                    }

                    public function offsetSet(mixed $id, mixed $value): void
                    {
                        $this->values[$id] = $value;
                        unset($this->resolved[$id]);
                    }

                    public function offsetUnset(mixed $id): void
                    {
                        unset($this->values[$id], $this->resolved[$id]);
                    }
                }
                PHP);
        }
    }
}
